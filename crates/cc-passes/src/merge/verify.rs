fn check(name: impl Into<String>, notes: &[String], counts: &[(&str, u64)]) -> Check {
    let mut c = Check::new(name, notes.is_empty());
    for (k, v) in counts {
        c = c.count(*k, *v);
    }
    for n in notes.iter().take(20) {
        c = c.note(n.clone());
    }
    if notes.len() > 20 {
        c = c.note(format!("… {} more", notes.len() - 20));
    }
    c
}

fn list(dir: &std::path::Path, ext: &str) -> Vec<String> {
    let mut v: Vec<String> = std::fs::read_dir(dir)
        .map(|r| {
            r.filter_map(|e| e.ok())
                .filter_map(|e| {
                    e.file_name()
                        .to_str()
                        .and_then(|n| n.strip_suffix(ext))
                        .map(str::to_string)
                })
                .collect()
        })
        .unwrap_or_default();
    v.sort();
    v
}

const WIDEN: &[&str] = &[
    "add",
    "subtract",
    "multiply",
    "negate",
    "and",
    "or",
    "xor",
    "not",
    "maximum",
    "minimum",
    "abs",
    "compare",
    "select",
    "divide",
    "remainder",
    "shift_left",
];

fn int(t: &str) -> Option<(bool, u32)> {
    if t == "i1" {
        return None;
    }
    if let Some(w) = t.strip_prefix("ui") {
        return w.parse().ok().map(|w| (false, w));
    }
    t.strip_prefix('i')
        .and_then(|w| w.parse().ok())
        .map(|w| (true, w))
}

/// `narrow` is served by `wide` in `widen` mode.
fn widens(
    narrow: &[String],
    wide: &[String],
    kind: BlockKind,
    op: &str,
    attrs: &BTreeMap<String, String>,
) -> bool {
    if narrow.len() != wide.len() {
        return false;
    }
    if kind == BlockKind::Op
        && (!WIDEN.contains(&op)
            || (op == "compare" && attrs.get("compare_type").map(String::as_str) == Some("UNSIGNED")))
    {
        return false;
    }
    narrow.iter().zip(wide).all(|(n, w)| {
        n == w || matches!((int(n), int(w)), (Some((sn, wn)), Some((sw, ww))) if sn == sw && wn <= ww)
    })
}

/// The node of a configuration binding (by name) in the unit.
fn configs_check(fu: &FuFile, cfgs: &[&ConfigFile], units: &HashMap<(&str, &str), &Unit>) -> Vec<String> {
    let mut bad = Vec::new();
    for c in cfgs {
        let Some(u) = units.get(&(c.unit.as_str(), c.tuple.as_str())) else {
            bad.push(format!("{}: no unit {} with tuple {}", fu.id, c.unit, c.tuple));
            continue;
        };
        let Some(k) = u.tuples.iter().position(|t| *t == c.tuple) else {
            bad.push(format!("{} {}: no tuple {}", fu.id, c.unit, c.tuple));
            continue;
        };
        let by_node: HashMap<&str, &Binding> = c.bindings.iter().map(|b| (b.node.as_str(), b)).collect();
        if by_node.len() != c.bindings.len() || c.bindings.len() != u.nodes.len() {
            bad.push(format!(
                "{} {} {}: bindings do not match the nodes one to one",
                fu.id, c.unit, c.tuple
            ));
            continue;
        }
        let blocks: BTreeSet<u32> = c.bindings.iter().map(|b| b.block).collect();
        if blocks.len() != c.bindings.len() {
            bad.push(format!(
                "{} {} {}: two nodes on one block",
                fu.id, c.unit, c.tuple
            ));
        }
        let sel: HashMap<(u32, u32), u32> = c.selects.iter().map(|s| ((s.block, s.port), s.select)).collect();
        let block_of = |n: &UNode| by_node.get(n.name.as_str()).map(|b| b.block);
        for n in &u.nodes {
            let Some(b) = by_node.get(n.name.as_str()) else {
                bad.push(format!("{} {}: node {} is not bound", fu.id, c.unit, n.name));
                continue;
            };
            let Some(blk) = fu.blocks.get(b.block as usize) else {
                bad.push(format!("{} {}: block {} does not exist", fu.id, c.unit, b.block));
                continue;
            };
            let sem = |m: &BTreeMap<String, String>| -> BTreeMap<String, String> {
                m.iter()
                    .filter(|(k, _)| *k != "value")
                    .map(|(k, v)| (k.clone(), v.clone()))
                    .collect()
            };
            if blk.kind != n.kind || blk.op != n.op || sem(&blk.attrs) != sem(&n.attrs) {
                bad.push(format!(
                    "{} {}: {} on block {} ({} {})",
                    fu.id, c.unit, n.name, b.block, blk.op, n.op
                ));
            }
            if b.types != n.sigs[k] {
                bad.push(format!(
                    "{} {} {}: {} types differ from the datapath",
                    fu.id, c.unit, c.tuple, n.name
                ));
            }
            let native = b.types == blk.types;
            let ok_mode = match b.mode {
                Mode::Native => native,
                Mode::Widen => !native && widens(&b.types, &blk.types, blk.kind, &blk.op, &blk.attrs),
            };
            if !ok_mode {
                bad.push(format!(
                    "{} {} {}: {} mode {:?} on {:?}",
                    fu.id, c.unit, c.tuple, n.name, b.mode, blk.types
                ));
            }
            if b.var != n.var {
                bad.push(format!("{} {}: {} variable", fu.id, c.unit, n.name));
            }
            // Every operand edge realized at its port and select.
            let ports: Vec<u32> = if n.kind == BlockKind::Op {
                b.ports.clone()
            } else {
                (0..n.args.len() as u32).collect()
            };
            let mut seen: BTreeSet<u32> = BTreeSet::new();
            if ports.len() != n.args.len() || !ports.iter().all(|p| seen.insert(*p)) {
                bad.push(format!("{} {}: {} ports {:?}", fu.id, c.unit, n.name, ports));
                continue;
            }
            if n.kind == BlockKind::Op
                && !n.commutative
                && ports.iter().enumerate().any(|(i, &p)| p as usize != i)
            {
                bad.push(format!(
                    "{} {}: {} exchanges the operands of a non-commutative op",
                    fu.id, c.unit, n.name
                ));
            }
            for (i, &(s, res)) in n.args.iter().enumerate() {
                let p = ports[i];
                let Some(srcs) = blk.sources.get(p as usize) else {
                    bad.push(format!("{} {}: block {} has no port {p}", fu.id, c.unit, b.block));
                    continue;
                };
                let k = if srcs.len() >= 2 {
                    match sel.get(&(b.block, p)) {
                        Some(&k) => k as usize,
                        None => {
                            bad.push(format!(
                                "{} {}: block {} port {p} has no select",
                                fu.id, c.unit, b.block
                            ));
                            continue;
                        }
                    }
                } else {
                    0
                };
                let want = block_of(&u.nodes[s as usize]).map(|blk| Source { block: blk, res });
                if srcs.get(k).copied() != want {
                    bad.push(format!(
                        "{} {}: {} operand {i} is not wired",
                        fu.id, c.unit, n.name
                    ));
                }
            }
        }
    }
    bad
}

fn wiring_check(fu: &FuFile, cfgs: &[&ConfigFile], units: &HashMap<(&str, &str), &Unit>) -> Vec<String> {
    let mut bad = Vec::new();
    let mut used: BTreeSet<(u32, u32, Source)> = BTreeSet::new();
    for c in cfgs {
        let Some(u) = units.get(&(c.unit.as_str(), c.tuple.as_str())) else {
            continue;
        };
        let by_node: HashMap<&str, &Binding> = c.bindings.iter().map(|b| (b.node.as_str(), b)).collect();
        for n in &u.nodes {
            let Some(b) = by_node.get(n.name.as_str()) else {
                continue;
            };
            for (i, &(s, res)) in n.args.iter().enumerate() {
                let p = if n.kind == BlockKind::Op {
                    b.ports.get(i).copied().unwrap_or(i as u32)
                } else {
                    i as u32
                };
                if let Some(sb) = by_node.get(u.nodes[s as usize].name.as_str()) {
                    used.insert((b.block, p, Source { block: sb.block, res }));
                }
            }
        }
    }
    let muxes: BTreeMap<(u32, u32), u32> = fu.muxes.iter().map(|m| ((m.block, m.port), m.inputs)).collect();
    for b in &fu.blocks {
        for (p, srcs) in b.sources.iter().enumerate() {
            for s in srcs {
                if !used.contains(&(b.id, p as u32, *s)) {
                    bad.push(format!(
                        "{}: block {} port {p}: source {:?} is used by no configuration",
                        fu.id, b.id, s
                    ));
                }
            }
            let m = muxes.get(&(b.id, p as u32)).copied();
            let ok = if srcs.len() >= 2 {
                m == Some(srcs.len() as u32)
            } else {
                m.is_none()
            };
            if !ok {
                bad.push(format!(
                    "{}: block {} port {p}: {} sources, multiplexer {m:?}",
                    fu.id,
                    b.id,
                    srcs.len()
                ));
            }
        }
    }
    bad
}

fn dag_check(fu: &FuFile) -> Vec<String> {
    let n = fu.blocks.len();
    let mut indeg = vec![0usize; n];
    let mut succ: Vec<Vec<usize>> = vec![Vec::new(); n];
    for b in &fu.blocks {
        let mut from: BTreeSet<usize> = BTreeSet::new();
        for s in b.sources.iter().flatten() {
            let src = s.block as usize;
            if src >= n {
                return vec![format!("{}: block {} reads block {src}", fu.id, b.id)];
            }
            if fu.blocks[src].kind != BlockKind::Acc {
                from.insert(src);
            }
        }
        for s in from {
            succ[s].push(b.id as usize);
            indeg[b.id as usize] += 1;
        }
    }
    let mut ready: Vec<usize> = (0..n).filter(|&i| indeg[i] == 0).collect();
    let mut seen = 0;
    while let Some(x) = ready.pop() {
        seen += 1;
        for &y in &succ[x] {
            indeg[y] -= 1;
            if indeg[y] == 0 {
                ready.push(y);
            }
        }
    }
    if seen == n {
        Vec::new()
    } else {
        vec![format!("{}: {} blocks on cycles", fu.id, n - seen)]
    }
}

fn close(a: f64, b: f64) -> bool {
    (a - b).abs() <= 1e-6 * (1.0 + a.abs().max(b.abs()))
}

fn area_check(fu: &FuFile, lib: &Lib) -> Vec<String> {
    let mut bad = Vec::new();
    let mut total = 0.0;
    for b in &fu.blocks {
        let literal = b.kind == BlockKind::Const && b.attrs.contains_key("value");
        let p = lib.block(b.kind, &b.op, &b.attrs, &b.types, literal);
        if !close(p.area_um2, b.price.area_um2) || !close(p.delay_ps, b.price.delay_ps) {
            bad.push(format!(
                "{}: block {} price {} vs {}",
                fu.id, b.id, b.price.area_um2, p.area_um2
            ));
        }
        total += p.area_um2;
    }
    let mut mux_delay: HashMap<(u32, u32), f64> = HashMap::new();
    for m in &fu.muxes {
        let w = fu.blocks.get(m.block as usize).map(|b| {
            let t = match b.kind {
                BlockKind::Op => b.types.get(m.port as usize),
                _ => b.types.first(),
            };
            bits(t.map(String::as_str).unwrap_or(""))
        });
        let p = lib.mux(m.inputs, w.unwrap_or(0));
        if Some(m.width) != w || !close(p.area_um2, m.price.area_um2) {
            bad.push(format!("{}: multiplexer at {}:{} price", fu.id, m.block, m.port));
        }
        total += p.area_um2;
        mux_delay.insert((m.block, m.port), p.delay_ps);
    }
    if !close(total, fu.area_um2) {
        bad.push(format!("{}: area {} recomputes to {total}", fu.id, fu.area_um2));
    }
    // Critical path, by memoized longest path over the stored sources.
    let n = fu.blocks.len();
    let mut at: Vec<Option<f64>> = vec![None; n];
    fn arrival(
        fu: &FuFile,
        b: usize,
        at: &mut Vec<Option<f64>>,
        md: &HashMap<(u32, u32), f64>,
        guard: usize,
    ) -> f64 {
        if let Some(x) = at[b] {
            return x;
        }
        if guard > fu.blocks.len() {
            return f64::INFINITY;
        }
        let blk = &fu.blocks[b];
        let mut t = 0.0f64;
        for (p, srcs) in blk.sources.iter().enumerate() {
            let m = md.get(&(b as u32, p as u32)).copied().unwrap_or(0.0);
            for s in srcs {
                let src = s.block as usize;
                let a = if fu.blocks[src].kind == BlockKind::Acc {
                    0.0
                } else {
                    arrival(fu, src, at, md, guard + 1)
                };
                t = t.max(a + m);
            }
        }
        let own = if blk.kind == BlockKind::Op {
            blk.price.delay_ps
        } else {
            0.0
        };
        at[b] = Some(t + own);
        t + own
    }
    let mut worst = 0.0f64;
    for b in 0..n {
        worst = worst.max(arrival(fu, b, &mut at, &mux_delay, 0));
    }
    if !close(worst, fu.depth_ps) {
        bad.push(format!("{}: depth {} recomputes to {worst}", fu.id, fu.depth_ps));
    }
    if worst > fu.bound_ps + 1e-6 {
        bad.push(format!("{}: depth {worst} over the bound {}", fu.id, fu.bound_ps));
    }
    bad
}

/// An independent exact search on a stored instance: the heaviest set closed under implications,
/// free of conflicts and no-goods (branch and bound, nodes in index order).
fn best(cert: &CliqueCert) -> Option<f64> {
    let n = cert.nodes.len();
    if n > 400 {
        return None;
    }
    let mut conf = vec![vec![false; n]; n];
    for &(a, b) in &cert.conflicts {
        if (a as usize) < n && (b as usize) < n {
            conf[a as usize][b as usize] = true;
            conf[b as usize][a as usize] = true;
        }
    }
    let mut needs: Vec<Vec<usize>> = vec![Vec::new(); n];
    for &(a, v) in &cert.implies {
        needs[a as usize].push(v as usize);
    }
    let w: Vec<f64> = cert.nodes.iter().map(|x| x.weight).collect();
    let mut target = vec![false; n];
    for v in needs.iter().flatten() {
        target[*v] = true;
    }
    struct S<'a> {
        conf: &'a [Vec<bool>],
        needs: &'a [Vec<usize>],
        w: &'a [f64],
        target: &'a [bool],
        ng: &'a [Vec<u32>],
        best: f64,
        steps: u64,
    }
    fn closure(s: &S, cur: &[usize]) -> Vec<usize> {
        let mut closed: Vec<usize> = cur.to_vec();
        for &x in cur {
            closed.extend(&s.needs[x]);
        }
        closed.sort_unstable();
        closed.dedup();
        closed
    }
    fn ok(s: &S, closed: &[usize]) -> bool {
        for (i, &x) in closed.iter().enumerate() {
            for &y in &closed[i + 1..] {
                if s.conf[x][y] {
                    return false;
                }
            }
        }
        !s.ng
            .iter()
            .any(|g| g.iter().all(|v| closed.binary_search(&(*v as usize)).is_ok()))
    }
    /// `cur` is feasible; its closure's weight is a candidate, and every closed extension adds only
    /// nodes outside the closure that are at or after `i` or implied by something.
    fn go(s: &mut S, i: usize, cur: &mut Vec<usize>) {
        s.steps += 1;
        if s.steps > 5_000_000 {
            return;
        }
        let closed = closure(s, cur);
        let cw: f64 = closed.iter().map(|&x| s.w[x]).sum();
        s.best = s.best.max(cw);
        if i == s.w.len() {
            return;
        }
        let rest: f64 = (0..s.w.len())
            .filter(|&j| closed.binary_search(&j).is_err() && (j >= i || s.target[j]))
            .map(|j| s.w[j])
            .sum();
        if cw + rest <= s.best + 1e-9 {
            return;
        }
        if closed.binary_search(&i).is_err() {
            cur.push(i);
            let c2 = closure(s, cur);
            if ok(s, &c2) {
                go(s, i + 1, cur);
            }
            cur.pop();
        }
        go(s, i + 1, cur);
    }
    let mut s = S {
        conf: &conf,
        needs: &needs,
        w: &w,
        target: &target,
        ng: &cert.nogoods,
        best: 0.0,
        steps: 0,
    };
    go(&mut s, 0, &mut Vec::new());
    (s.steps <= 5_000_000).then_some(s.best)
}

fn clique_check(cert: &CliqueCert) -> Vec<String> {
    let mut bad = Vec::new();
    let n = cert.nodes.len() as u32;
    let chosen: BTreeSet<u32> = cert.chosen.iter().copied().collect();
    if chosen.iter().any(|&x| x >= n) {
        return vec!["a chosen node does not exist".into()];
    }
    for &(a, b) in &cert.conflicts {
        if chosen.contains(&a) && chosen.contains(&b) {
            bad.push(format!("nodes {a} and {b} conflict"));
        }
    }
    for &(a, v) in &cert.implies {
        if chosen.contains(&a) && !chosen.contains(&v) {
            bad.push(format!("arc {a} without its end {v}"));
        }
    }
    for g in &cert.nogoods {
        if g.iter().all(|x| chosen.contains(x)) {
            bad.push(format!("no-good {g:?} chosen"));
        }
    }
    let w: f64 = chosen.iter().map(|&x| cert.nodes[x as usize].weight).sum();
    if !close(w, cert.objective) {
        bad.push(format!("objective {} recomputes to {w}", cert.objective));
    }
    if cert.optimal
        && let Some(b) = best(cert)
        && b > cert.objective + 1e-6 * (1.0 + b.abs())
    {
        bad.push(format!("claimed optimal at {}, {b} exists", cert.objective));
    }
    bad
}

pub(super) fn verify(ctx: &PassContext) -> Result<VerifyReport, PassError> {
    let cfg: MergeConfig = ctx.options()?;
    let mut r = VerifyReport::new(ctx.name());
    let out = ctx.output(MERGE)?;
    let inputs = load(ctx, &cfg)?;
    let lib = Lib::new(&inputs.library, &cfg.kit).map_err(PassError::failed)?;
    // A unit split by tuple types has one part per group of tuples: look parts up by (unit, tuple).
    let mut units: HashMap<(&str, &str), &Unit> = HashMap::new();
    for u in &inputs.units {
        for t in &u.tuples {
            units.insert((u.id.as_str(), t.as_str()), u);
        }
    }
    let dps: HashMap<&str, &Datapath> = inputs.datapaths.iter().map(|d| (d.id.as_str(), d)).collect();

    // Files.
    let mut files_bad = Vec::new();
    let mut fus: Vec<FuFile> = Vec::new();
    for id in list(&out.path("fus")?, ".json") {
        match out.read_json::<FuFile>(&format!("fus/{id}.json")) {
            Ok(f) => fus.push(f),
            Err(e) => files_bad.push(format!("fus/{id}.json: {e}")),
        }
    }
    let mut configs: Vec<ConfigFile> = Vec::new();
    for f in &fus {
        for c in &f.covers {
            for t in &c.tuples {
                let p = format!("configs/{}/{}/{t}.json", f.id, c.unit);
                match out.read_json::<ConfigFile>(&p) {
                    Ok(x) if x.fu == f.id && x.unit == c.unit && x.tuple == *t => configs.push(x),
                    Ok(_) => files_bad.push(format!("{p}: names another configuration")),
                    Err(e) => files_bad.push(format!("{p}: {e}")),
                }
            }
        }
    }
    let mut arrays: Vec<ArrayFile> = Vec::new();
    for id in list(&out.path("arrays")?, ".json") {
        match out.read_json::<ArrayFile>(&format!("arrays/{id}.json")) {
            Ok(a) => arrays.push(a),
            Err(e) => files_bad.push(format!("arrays/{id}.json: {e}")),
        }
    }
    let mut traces: Vec<Trace> = Vec::new();
    for f in Family::ALL {
        match out.read_json::<Trace>(&format!("trace/{}.json", f.name())) {
            Ok(t) => traces.push(t),
            Err(e) => files_bad.push(format!("trace/{}.json: {e}", f.name())),
        }
    }
    r.push(check(
        "files",
        &files_bad,
        &[
            ("units", fus.len() as u64),
            ("configurations", configs.len() as u64),
            ("arrays", arrays.len() as u64),
        ],
    ));

    // Per unit: configurations, wiring, cycles, prices.
    let mut by_fu: HashMap<&str, Vec<&ConfigFile>> = HashMap::new();
    for c in &configs {
        by_fu.entry(c.fu.as_str()).or_default().push(c);
    }
    let per: Vec<PerUnit> = fus
        .par_iter()
        .map(|f| {
            let cs = by_fu.get(f.id.as_str()).cloned().unwrap_or_default();
            (
                f.id.clone(),
                configs_check(f, &cs, &units),
                wiring_check(f, &cs, &units),
                dag_check(f),
                area_check(f, &lib),
            )
        })
        .collect();
    for (id, c, w, d, a) in &per {
        r.push(check(format!("{id}:configs"), c, &[]));
        r.push(check(format!("{id}:wiring"), w, &[]));
        r.push(check(format!("{id}:dag"), d, &[]));
        r.push(check(format!("{id}:area"), a, &[]));
    }

    // Depth bounds: the derived bound is the deepest single unit in whole periods.
    let mut bound_bad = Vec::new();
    if cfg.max_logic_depth <= 0.0 {
        for t in &traces {
            let fam: Vec<(usize, &Unit)> = inputs
                .units
                .iter()
                .enumerate()
                .filter(|(_, u)| u.family == t.family)
                .collect();
            let mut worst = 0.0f64;
            for (i, u) in &fam {
                if let Ok(f) = Fu::single(u, *i as u32) {
                    worst = worst.max(cost(&f, &inputs.units, &lib).depth);
                }
            }
            let p = lib.period_ps.max(1.0);
            let want = (worst / p).ceil().max(1.0) * p;
            if !close(want, t.bound_ps) {
                bound_bad.push(format!(
                    "{}: bound {} recomputes to {want}",
                    t.family.name(),
                    t.bound_ps
                ));
            }
        }
    }
    for f in &fus {
        let tb = traces.iter().find(|t| t.family == f.family).map(|t| t.bound_ps);
        if tb.is_some_and(|b| !close(b, f.bound_ps)) {
            bound_bad.push(format!("{}: bound {} is not the family's", f.id, f.bound_ps));
        }
    }
    r.push(check("bounds", &bound_bad, &[]));

    // Proofs: regenerated byte for byte, stored results, the second solver.
    let fu_by: HashMap<&str, &FuFile> = fus.iter().map(|f| (f.id.as_str(), f)).collect();
    let mut queries: Vec<Result<proofs::Query, String>> = configs
        .par_iter()
        .map(|c| {
            let dp = dps
                .get(c.class.as_str())
                .ok_or_else(|| format!("{}: no datapath", c.class))?;
            let t = dp
                .tuples
                .iter()
                .find(|t| t.name == c.tuple)
                .ok_or_else(|| format!("{}: no tuple {}", c.class, c.tuple))?;
            proofs::config_query(fu_by[c.fu.as_str()], c, dp, t)
        })
        .collect();
    let mut zq: Vec<Result<proofs::Query, String>> = Vec::new();
    for a in &arrays {
        for cv in &a.covers {
            for t in &cv.tuples {
                let q = proofs::array_query(a, &cv.class, t);
                if t.mode == ArrayMode::Compose {
                    zq.push(q)
                } else {
                    queries.push(q)
                }
            }
        }
    }
    let (solver, runner, location) = smt(ctx)?;
    let mut proof_bad = Vec::new();
    let mut files = Vec::new();
    let mut zfiles = Vec::new();
    let nq = queries.len();
    for (i, q) in queries.iter().chain(&zq).enumerate() {
        let want = if i < nq { solver } else { Solver::Z3 };
        match q {
            Ok(q) => {
                let stored =
                    std::fs::read_to_string(out.path(&format!("proofs/{}", q.file))?).unwrap_or_default();
                if stored != q.text {
                    proof_bad.push(format!("{}: differs from the regenerated query", q.file));
                }
                match out.read_json::<ProofResult>(&format!("proofs/{}", q.file.replace(".smt2", ".result")))
                {
                    Ok(res) => {
                        if res.query_hash != cc_smt::query_hash(&q.text)
                            || res.solver != want
                            || !res.verdict.is_unsat()
                        {
                            proof_bad.push(format!(
                                "{}: result {:?} by {}",
                                q.file,
                                res.verdict,
                                res.solver.name()
                            ));
                        }
                    }
                    Err(e) => proof_bad.push(format!("{}: {e}", q.file)),
                }
                if i < nq {
                    files.push(q.file.clone());
                } else {
                    zfiles.push(q.file.clone());
                }
            }
            Err(e) => proof_bad.push(e.clone()),
        }
    }
    // Composed steps: Z3 again (as the datapaths' encoding lemmas).
    if !zfiles.is_empty() {
        match cc_smt::run_sharded(
            &runner,
            &location,
            Solver::Z3,
            &out.path("proofs")?,
            &zfiles,
            cfg.compose_timeout_s,
            ctx.resources().threads.max(1),
        ) {
            Ok(b) => {
                for f in &zfiles {
                    match b.verdicts.get(f) {
                        Some(v) if v.is_unsat() => {}
                        v => proof_bad.push(format!("{f}: z3 says {v:?}")),
                    }
                }
            }
            Err(e) => proof_bad.push(format!("z3: {e}")),
        }
    }
    let threads = ctx.resources().threads.max(1);
    if !files.is_empty() {
        match cc_smt::run_sharded(
            &runner,
            &location,
            solver.other(),
            &out.path("proofs")?,
            &files,
            ctx.smt().timeout_s,
            threads,
        ) {
            Ok(b) => {
                for f in &files {
                    match b.verdicts.get(f) {
                        Some(v) if v.is_unsat() => {}
                        v => proof_bad.push(format!("{f}: {} says {v:?}", solver.other().name())),
                    }
                }
            }
            Err(e) => proof_bad.push(format!("{}: {e}", solver.other().name())),
        }
    }
    r.push(check(
        "proofs",
        &proof_bad,
        &[("queries", files.len() as u64), ("composed", zfiles.len() as u64)],
    ));
    r.push(sanity(ctx, &fus, &configs, &dps, solver, &runner, &location)?);

    // Arrays.
    let isp = ctx.input(ITERATION_SPACE)?;
    let routing: Routing = isp.read_json("routing.json")?;
    let flow: HashMap<&str, (Route, Option<&String>)> = routing
        .classes
        .iter()
        .map(|c| (c.id.as_str(), (c.route, c.dataflow.as_ref())))
        .collect();
    let mut arr_bad = Vec::new();
    for a in &arrays {
        for cv in &a.covers {
            match flow.get(cv.class.as_str()) {
                Some((Route::Template, Some(d))) if **d == a.dataflow => {}
                other => arr_bad.push(format!("{} {}: route/dataflow {other:?}", a.id, cv.class)),
            }
            let embeds = cv.class == a.host || inputs.embeds.contains(&(cv.class.clone(), a.host.clone()));
            if !embeds || cv.embedded != (cv.class != a.host) {
                arr_bad.push(format!("{} {}: does not embed into {}", a.id, cv.class, a.host));
            }
            for t in &cv.tuples {
                if t.mode == ArrayMode::Compose {
                    let w = t
                        .types
                        .get(if t.split.as_deref() == Some("lhs") { 0 } else { 1 })
                        .map(|x| bits(x))
                        .unwrap_or(0);
                    if t.pieces.iter().sum::<u32>() != w || t.passes as usize != t.pieces.len() {
                        arr_bad.push(format!(
                            "{} {} {}: pieces {:?}",
                            a.id, cv.class, t.tuple, t.pieces
                        ));
                    }
                }
            }
        }
    }
    r.push(check("arrays", &arr_bad, &[("arrays", arrays.len() as u64)]));

    // Cliques.
    let mut cq_bad = Vec::new();
    let mut certs = 0u64;
    for t in &traces {
        for s in &t.steps {
            let Some(f) = &s.clique.certificate else { continue };
            certs += 1;
            match out.read_json::<CliqueCert>(&format!("cliques/{}/{f}", t.family.name())) {
                Ok(c) => {
                    for b in clique_check(&c) {
                        cq_bad.push(format!("{} step {}: {b}", t.family.name(), s.step));
                    }
                    if !close(c.objective, s.clique.objective) {
                        cq_bad.push(format!(
                            "{} step {}: objective differs from the trace",
                            t.family.name(),
                            s.step
                        ));
                    }
                }
                Err(e) => cq_bad.push(format!("{} {f}: {e}", t.family.name())),
            }
        }
    }
    r.push(check("cliques", &cq_bad, &[("certificates", certs)]));

    // Trace.
    let mut tr_bad = Vec::new();
    for t in &traces {
        let fam: Vec<&FuFile> = fus.iter().filter(|f| f.family == t.family).collect();
        let area: f64 = fam.iter().map(|f| f.area_um2).sum();
        let last = t.steps.last().map(|s| s.area_um2).unwrap_or(t.initial_area_um2);
        let units = t.initial_units - t.steps.len() as u64;
        if !close(area, last) || fam.len() as u64 != units {
            tr_bad.push(format!(
                "{}: {} units of {area} µm², the trace ends at {units} of {last}",
                t.family.name(),
                fam.len()
            ));
        }
        let n_units = inputs.units.iter().filter(|u| u.family == t.family).count() as u64;
        if t.initial_units != n_units {
            tr_bad.push(format!(
                "{}: {} units, {n_units} in the family",
                t.family.name(),
                t.initial_units
            ));
        }
    }
    r.push(check("trace", &tr_bad, &[]));

    // Coverage, recomputed.
    let have: BTreeSet<(&str, &str)> = configs
        .iter()
        .map(|c| (c.unit.as_str(), c.tuple.as_str()))
        .collect();
    let mut arr_tuples: BTreeSet<(&str, &str)> = BTreeSet::new();
    for a in &arrays {
        for cv in &a.covers {
            for t in &cv.tuples {
                arr_tuples.insert((cv.class.as_str(), t.tuple.as_str()));
            }
        }
    }
    let mut cov_bad = Vec::new();
    for dp in &inputs.datapaths {
        let mut stages: BTreeSet<String> = BTreeSet::new();
        match dp.route {
            Route::Datapath => {
                stages.insert(dp.id.clone());
            }
            Route::Template => {
                for v in &dp.vertices {
                    stages.insert(match v.stage {
                        crate::datapaths::json::Stage::Prologue { port } => {
                            format!("{}/prologue{port}", dp.id)
                        }
                        _ => format!("{}/epilogue", dp.id),
                    });
                }
                for t in &dp.tuples {
                    if !arr_tuples.contains(&(dp.id.as_str(), t.name.as_str())) {
                        cov_bad.push(format!("{} {}: no array", dp.id, t.name));
                    }
                }
            }
        }
        for s in &stages {
            for t in &dp.tuples {
                if !have.contains(&(s.as_str(), t.name.as_str())) {
                    cov_bad.push(format!("{s} {}: no configuration", t.name));
                }
            }
        }
    }
    let cov: Result<CoverageFile, _> = out.read_json("coverage.json");
    match &cov {
        Ok(c) if c.total == inputs.datapaths.len() as u64 && c.covered == c.total => {}
        Ok(c) => cov_bad.push(format!("coverage.json: {}/{}", c.covered, c.total)),
        Err(e) => cov_bad.push(format!("coverage.json: {e}")),
    }
    r.push(check(
        "coverage",
        &cov_bad,
        &[("classes", inputs.datapaths.len() as u64)],
    ));
    Ok(r)
}

/// A configuration with a wrong select must be refuted by both solvers.
fn sanity(
    ctx: &PassContext,
    fus: &[FuFile],
    configs: &[ConfigFile],
    dps: &HashMap<&str, &Datapath>,
    solver: Solver,
    runner: &cc_core::runner::BoundRunner,
    location: &cc_smt::Location,
) -> Result<Check, PassError> {
    let fu_by: HashMap<&str, &FuFile> = fus.iter().map(|f| (f.id.as_str(), f)).collect();
    // The first configuration whose select can move to a source of the same type giving another value.
    let mut found = None;
    'outer: for c in configs {
        let fu = fu_by[c.fu.as_str()];
        for (k, s) in c.selects.iter().enumerate() {
            let n = fu.blocks[s.block as usize].sources[s.port as usize].len() as u32;
            for alt in 0..n {
                if alt == s.select {
                    continue;
                }
                let mut bad = c.clone();
                bad.selects[k].select = alt;
                let Some(dp) = dps.get(c.class.as_str()) else {
                    continue;
                };
                let Some(t) = dp.tuples.iter().find(|t| t.name == c.tuple) else {
                    continue;
                };
                if let Ok(q) = proofs::config_query(fu, &bad, dp, t) {
                    found = Some(q);
                    break 'outer;
                }
            }
        }
    }
    let Some(q) = found else {
        return Ok(
            Check::new("solver_sanity", true).note("no multiplexer with a well-typed alternative source")
        );
    };
    let dir = ctx.dir().path().join("cache").join("sanity");
    std::fs::create_dir_all(&dir).map_err(|e| PassError::failed(format!("sanity: {e}")))?;
    let file = "sanity.smt2".to_string();
    std::fs::write(dir.join(&file), &q.text).map_err(|e| PassError::failed(format!("sanity: {e}")))?;
    let mut notes = Vec::new();
    for s in [solver, solver.other()] {
        let b = cc_smt::run_batch(
            runner,
            location,
            s,
            &dir,
            std::slice::from_ref(&file),
            ctx.smt().timeout_s,
        )?;
        match b.verdicts.get(&file) {
            Some(Verdict::Sat { .. }) => {}
            v => notes.push(format!("{}: {v:?} (expected sat)", s.name())),
        }
    }
    Ok(check("solver_sanity", &notes, &[]).note(format!("mutated: {}", q.file)))
}
