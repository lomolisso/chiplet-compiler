//! Independent checks of the merge (design §5, docs/passes/merge.md §6). They never run the
//! compatibility graph, the clique solvers, the rebuild or the agglomeration; they read the stored units
//! and configurations and check them against the datapaths, the library and the solvers.
//!
//! - `files`: every unit, configuration, array, trace and result file parses;
//! - `<F>:configs`: every configuration binds each datapath node to one block of the same kind, op and
//!   attributes (injectively), at the node's types, `native` exactly when they are the block's and
//!   `widen` only for narrower integers of one signedness on an operator that allows it; every datapath
//!   edge is a source of the block port it uses, at the stored select;
//! - `<F>:wiring`: every source of every port is used by some configuration, a port with two or more
//!   sources has a multiplexer of that size and no other port has one;
//! - `<F>:dag`: the unit is acyclic (edges out of accumulator registers excepted);
//! - `<F>:area`: block and multiplexer prices recomputed from `library.json`, their sum is the area;
//!   the critical path recomputed is the stored depth and within the family's bound;
//! - `proofs`: every query is regenerated byte for byte from the stored unit and configuration (and the
//!   datapath), every result is the configured solver's `unsat` for that text, and the second solver
//!   agrees on all of them;
//! - `solver_sanity`: one configuration with a wrong multiplexer select gives `sat` in both solvers;
//! - `arrays`: every covered class is a template class with the array's dataflow, the host or a guest of
//!   the host in `embedding.json`; composed pieces add up to the operand width;
//! - `cliques`: every stored compatibility graph's solution is a clique closed under arc ends, avoids
//!   every no-good, has the stored weight, and when it is claimed optimal, an independent branch and
//!   bound finds no heavier one;
//! - `trace`: per family, the units left and the area after the last step are the stored units';
//! - `coverage`: recomputed from the datapaths: every datapath class has a configuration per tuple,
//!   every template class an array per tuple and a configuration per tuple of every non-empty stage.

