/// The environment's directory (`build/.env/`): `chipc doctor` writes the `.db` files and the merged
/// ASAP7 Liberty there.
pub fn env_dir(ctx: &PassContext) -> PassDir {
    ArtifactStore::new(ctx.resolve(&ctx.paths().build_dir)).pass_dir(ENV_DIR)
}

fn missing(what: &Path) -> String {
    format!("{} is missing: run `chipc doctor` first", what.display())
}

/// The kits of `cfg.pdks`, with what the rows record about them.
pub fn kits(ctx: &PassContext, cfg: &CharacterizeConfig) -> Result<Vec<(Kit, KitInfo)>, String> {
    let env = env_dir(ctx);
    let db_dir = env.out_dir().join("pdk_db");
    let mut out = Vec::new();
    for name in &cfg.pdks {
        let liberty = match name.as_str() {
            "nangate45" => ctx.resolve(
                ctx.paths()
                    .nangate45_lib
                    .as_deref()
                    .ok_or("paths.nangate45_lib is unset (config.local.toml)")?,
            ),
            "asap7" => env
                .out_dir()
                .join("pdk_lib")
                .join(format!("{}.lib", asap7_merged_name(&ctx.tools().pdk))),
            k => return Err(format!("unknown kit {k}")),
        };
        if !liberty.is_file() {
            return Err(missing(&liberty));
        }
        let lib = pdk_db::read_library(&liberty).map_err(|e| e.to_string())?;
        let db = db_dir.join(lib.db_file());
        if !db.is_file() {
            return Err(missing(&db));
        }
        let text = std::fs::read_to_string(&liberty).map_err(|e| format!("{}: {e}", liberty.display()))?;
        let cell = cfg
            .driving_cell
            .get(name)
            .ok_or_else(|| format!("driving_cell has no entry for {name}"))?;
        let kit = Kit::from_liberty(name, &text, liberty.clone(), db.clone(), cell, cfg.load_fanout)?;
        let hash = |p: &Path| canon::hash_file(p).map_err(|e| e.to_string());
        let info = KitInfo {
            name: name.clone(),
            corner: kit.corner.clone(),
            lib_name: kit.lib_name.clone(),
            liberty: liberty.display().to_string(),
            liberty_hash: hash(&liberty)?,
            db: db.display().to_string(),
            db_hash: hash(&db)?,
            time_unit_ps: kit.time_unit_ps,
            driving_cell: kit.driving_cell.clone(),
            load: kit.load,
        };
        out.push((kit, info));
    }
    Ok(out)
}

/// The versions of the licensed tools as `chipc doctor` recorded them (its manifest).
pub fn eda_versions(ctx: &PassContext) -> BTreeMap<String, String> {
    env_dir(ctx)
        .read_manifest()
        .ok()
        .flatten()
        .map(|m| m.tool_versions)
        .unwrap_or_default()
}

/// A design per primitive with RTL: its own file after its dependencies'.
pub fn design(p: &Primitive) -> Design {
    let mut files: Vec<String> = p.deps.iter().map(|d| format!("{d}.v")).collect();
    files.push(format!("{}.v", p.id));
    Design {
        id: p.id.clone(),
        files,
        clocked: p.clocked,
    }
}

const RTL_SCRIPT: &str = r#"#!/bin/bash
# Generated by chipc characterize: DSLX -> IR -> optimized IR -> combinational Verilog.
set -u
for x in *.x; do
  id="${x%.x}"
  if ir_converter_main --dslx_stdlib_path="$XLS_STDLIB" --top="$id" "$x" > "$id.ir" 2> "$id.err"; then
    top="$(sed -n 's/^top fn \([^(]*\)(.*/\1/p' "$id.ir")"
    if opt_main "$id.ir" --top="$top" > "$id.opt.ir" 2>> "$id.err" \
       && codegen_main "$id.opt.ir" --top="$top" --generator=combinational --use_system_verilog=false \
            --module_name="$id" --output_verilog_path="$id.v" 2>> "$id.err"; then
      :
    else
      echo "Error: optimization or codegen failed on $id"
    fi
  else
    echo "Error: IR conversion failed on $id"
  fi
done
echo "@@done"
"#;

/// RTL for every primitive with a source: Verilog sources as they are, DSLX through XLS in one container.
/// The job directory is named by the hash of the sources and the image, so a rerun reuses it.
pub fn rtl(ctx: &PassContext, cat: &[Primitive]) -> Result<PathBuf, PassError> {
    let fail = |e: String| PassError::failed(e);
    let mut key = format!("rtl\n{}\n{RTL_SCRIPT}", image(ctx));
    for p in cat {
        if let Some(s) = &p.source {
            key.push_str(&format!("{}\n{:?}\n", p.id, s));
        }
    }
    let dir = ctx.dir().path().join("eda").join(format!("rtl-{}", short(&key)));
    let done = dir.join("rtl.done");
    if done.is_file() {
        return Ok(dir);
    }
    std::fs::create_dir_all(&dir).map_err(|e| fail(format!("{}: {e}", dir.display())))?;
    for p in cat {
        let (name, text) = match &p.source {
            Some(Source::Dslx(t)) => (format!("{}.x", p.id), t),
            Some(Source::Verilog(t)) => (format!("{}.v", p.id), t),
            None => continue,
        };
        write(&dir.join(name), text)?;
    }
    write(&dir.join("gen.sh"), RTL_SCRIPT)?;
    let inv = Invocation::new("xls-rtl", "bash")
        .arg("gen.sh")
        .cwd("/work")
        .mount(Mount {
            src: dir.clone(),
            dst: "/work".into(),
            readonly: false,
        });
    let o = ctx.docker().run(&inv)?;
    let out = o.stdout_string().unwrap_or_default();
    if !o.success() || !out.contains("@@done") {
        return Err(fail(format!(
            "RTL generation failed (exit {:?}); see {}",
            o.exit_code,
            o.stdout.display()
        )));
    }
    let errs = parse::errors(&out);
    if !errs.is_empty() {
        return Err(fail(format!("RTL generation: {}", errs.join("; "))));
    }
    for p in cat.iter().filter(|p| p.source.is_some()) {
        let v = dir.join(format!("{}.v", p.id));
        if std::fs::metadata(&v).map(|m| m.len() == 0).unwrap_or(true) {
            return Err(fail(format!(
                "no RTL for {}: see {}",
                p.id,
                dir.join(format!("{}.err", p.id)).display()
            )));
        }
    }
    write(&done, "ok\n")?;
    Ok(dir)
}

fn lib_file(kit: &Kit) -> String {
    kit.liberty
        .file_name()
        .map(|f| f.to_string_lossy().into_owned())
        .unwrap_or_default()
}

fn image(ctx: &PassContext) -> String {
    let d = &ctx.tools().docker;
    format!("{}:{}", d.image, d.tag)
}

fn short(s: &str) -> String {
    canon::hash_bytes(s.as_bytes()).chars().take(16).collect()
}

fn write(p: &Path, text: &str) -> Result<(), PassError> {
    if let Some(d) = p.parent() {
        std::fs::create_dir_all(d).map_err(|e| PassError::failed(format!("{}: {e}", d.display())))?;
    }
    std::fs::write(p, text).map_err(|e| PassError::failed(format!("{}: {e}", p.display())))
}

/// One tool session: a batch of designs on one kit at one timing point.
#[derive(Debug, Clone)]
pub struct Job {
    pub kit: usize,
    pub target: String,
    pub period_ps: f64,
    pub designs: Vec<Design>,
    pub dir: PathBuf,
    /// File name → text of every script.
    pub scripts: Vec<(String, String)>,
}

/// What a finished job directory records.
#[derive(Debug, Clone, Serialize, Deserialize)]
struct Done {
    seconds: f64,
}

/// The jobs of a run, in a fixed order (kit, target, batch).
pub fn jobs(
    ctx: &PassContext,
    cfg: &CharacterizeConfig,
    kits: &[(Kit, KitInfo)],
    designs: &[Design],
    rtl_dir: &Path,
) -> Result<Vec<Job>, PassError> {
    let alib = ctx.dir().path().join("alib");
    let preamble = |tool: EdaTool| tool.cap_preamble(&job_caps(ctx, cfg)).join("\n");
    let mut out = Vec::new();
    for (ki, (kit, info)) in kits.iter().enumerate() {
        for target in &cfg.targets {
            let period = cfg.period_ps(&kit.name, target).map_err(PassError::failed)?;
            for chunk in designs.chunks(cfg.batch) {
                let mut scripts = Vec::new();
                match cfg.tool {
                    Tool::Dc => {
                        scripts.push((
                            "syn.tcl".into(),
                            eda::scripts::dc(&preamble(EdaTool::Dc), kit, chunk, period, &alib),
                        ));
                        scripts.push((
                            "lec.tcl".into(),
                            eda::scripts::formality(&preamble(EdaTool::Fm), kit, chunk),
                        ));
                    }
                    Tool::Genus => {
                        scripts.push((
                            "syn.tcl".into(),
                            eda::scripts::genus(&preamble(EdaTool::Genus), kit, chunk, period),
                        ));
                        for d in chunk {
                            scripts.push((
                                format!("{}.do", d.id),
                                eda::scripts::conformal(&preamble(EdaTool::Lec), kit, d),
                            ));
                        }
                    }
                    Tool::Yosys => {
                        scripts.push((
                            "run.sh".into(),
                            eda::scripts::yosys(&format!("/kit/{}", lib_file(kit)), chunk, period),
                        ));
                    }
                }
                let mut key = format!(
                    "{}\n{}\n{}\n{}\n",
                    cfg.tool.name(),
                    info.liberty_hash,
                    info.db_hash,
                    image(ctx)
                );
                for (f, t) in &scripts {
                    key.push_str(&format!("{f}\n{t}\n"));
                }
                for d in chunk {
                    for f in &d.files {
                        let text = std::fs::read_to_string(rtl_dir.join(f))
                            .map_err(|e| PassError::failed(format!("{f}: {e}")))?;
                        key.push_str(&format!("{f}\n{text}\n"));
                    }
                }
                let dir = ctx
                    .dir()
                    .path()
                    .join("eda")
                    .join(format!("{}-{target}-{}", kit.name, short(&key)));
                out.push(Job {
                    kit: ki,
                    target: target.clone(),
                    period_ps: period,
                    designs: chunk.to_vec(),
                    dir,
                    scripts,
                });
            }
        }
    }
    Ok(out)
}

/// Caps of one tool session: the pass's memory split over its parallel sessions, `cores` CPUs.
fn job_caps(ctx: &PassContext, cfg: &CharacterizeConfig) -> Caps {
    let r = ctx.resources();
    let par = r.threads.max(1) as f64;
    Caps {
        memory_gb: (r.memory_gb / par).max(1.0),
        cpus: f64::from(cfg.cores),
        timeout_s: r.timeout_min * 60.0,
        pids_limit: 1024,
    }
}

/// Run every job not already done, `threads` at a time (the license semaphore bounds the EDA calls).
/// Returns (run, reused, tool seconds).
pub fn run_jobs(
    ctx: &PassContext,
    cfg: &CharacterizeConfig,
    kits: &[(Kit, KitInfo)],
    jobs: &[Job],
    rtl_dir: &Path,
) -> Result<(u64, u64, f64), PassError> {
    let caps = job_caps(ctx, cfg);
    let pool = rayon::ThreadPoolBuilder::new()
        .num_threads(ctx.resources().threads.max(1))
        .build()
        .map_err(|e| PassError::failed(e.to_string()))?;
    let results: Vec<Result<Option<f64>, PassError>> = pool.install(|| {
        jobs.par_iter()
            .with_max_len(1)
            .map(|j| {
                ctx.check_cancelled()?;
                run_job(ctx, cfg, &kits[j.kit].0, j, rtl_dir, &caps)
            })
            .collect()
    });
    let (mut ran, mut reused, mut secs) = (0u64, 0u64, 0.0);
    for r in results {
        match r? {
            Some(s) => {
                ran += 1;
                secs += s;
            }
            None => reused += 1,
        }
    }
    Ok((ran, reused, secs))
}

fn run_job(
    ctx: &PassContext,
    cfg: &CharacterizeConfig,
    kit: &Kit,
    j: &Job,
    rtl_dir: &Path,
    caps: &Caps,
) -> Result<Option<f64>, PassError> {
    let done = j.dir.join("job.done");
    if done.is_file() {
        return Ok(None);
    }
    let t0 = Instant::now();
    std::fs::create_dir_all(j.dir.join("rtl")).map_err(|e| PassError::failed(e.to_string()))?;
    for d in &j.designs {
        for f in &d.files {
            std::fs::copy(rtl_dir.join(f), j.dir.join("rtl").join(f))
                .map_err(|e| PassError::failed(format!("{f}: {e}")))?;
        }
    }
    for (f, t) in &j.scripts {
        write(&j.dir.join(f), t)?;
    }
    let eda = || ctx.eda().with_caps(*caps);
    let keep = |o: &cc_core::runner::ToolOutcome, name: &str| -> Result<(), PassError> {
        if let Some(k) = &o.killed {
            return Err(PassError::failed(format!(
                "{}: {name} killed ({k:?})",
                j.dir.display()
            )));
        }
        std::fs::copy(&o.stdout, j.dir.join(name)).map_err(|e| PassError::failed(e.to_string()))?;
        Ok(())
    };
    match cfg.tool {
        Tool::Dc => {
            let o = eda().run(
                &Invocation::new("dc_shell", EdaTool::Dc.program())
                    .args(EdaTool::Dc.batch_args("syn.tcl"))
                    .cwd(&j.dir),
            )?;
            keep(&o, "synth.log")?;
            let o = eda().run(
                &Invocation::new("fm_shell", EdaTool::Fm.program())
                    .args(["-work_path", "fm"])
                    .args(EdaTool::Fm.batch_args("lec.tcl"))
                    .cwd(&j.dir),
            )?;
            keep(&o, "lec.log")?;
        }
        Tool::Genus => {
            let o = eda().run(
                &Invocation::new("genus", EdaTool::Genus.program())
                    .args([
                        "-batch",
                        "-no_gui",
                        "-disable_user_startup",
                        "-log",
                        "genus",
                        "-files",
                        "syn.tcl",
                    ])
                    .cwd(&j.dir),
            )?;
            keep(&o, "synth.log")?;
            for d in &j.designs {
                let o = eda().run(
                    &Invocation::new("lec", EdaTool::Lec.program())
                        .args(EdaTool::Lec.batch_args(&format!("{}.do", d.id)))
                        .cwd(&j.dir),
                )?;
                if let Some(k) = &o.killed {
                    return Err(PassError::failed(format!(
                        "{}: lec killed ({k:?})",
                        j.dir.display()
                    )));
                }
            }
        }
        Tool::Yosys => {
            let lib_dir = kit.liberty.parent().unwrap_or(Path::new("/"));
            let inv = Invocation::new("yosys", "bash")
                .arg("run.sh")
                .cwd("/work")
                .mount(Mount {
                    src: j.dir.clone(),
                    dst: "/work".into(),
                    readonly: false,
                })
                .mount(Mount {
                    src: lib_dir.to_path_buf(),
                    dst: "/kit".into(),
                    readonly: true,
                });
            let o = ctx.docker().with_caps(Caps { cpus: 1.0, ..*caps }).run(&inv)?;
            keep(&o, "synth.log")?;
        }
    }
    let secs = t0.elapsed().as_secs_f64();
    write(
        &done,
        &serde_json::to_string(&Done { seconds: secs }).unwrap_or_default(),
    )?;
    Ok(Some(secs))
}

/// A design's problems found while reading its job (empty: the row stands).
pub type Problems = Vec<String>;

/// The rows of one job, its files copied into `out/library/` (`out_root`), and each design's problems.
pub fn rows(
    cfg: &CharacterizeConfig,
    kit: &Kit,
    j: &Job,
    cat: &BTreeMap<&str, &Primitive>,
    out_root: &Path,
) -> Result<Vec<(Row, Problems)>, PassError> {
    let read = |f: &str| std::fs::read_to_string(j.dir.join(f)).unwrap_or_default();
    let synth = parse::segments(&read("synth.log"));
    let lec_log = parse::segments(&read("lec.log"));
    let mut out = Vec::new();
    for d in &j.designs {
        let p = cat[d.id.as_str()];
        let id = &d.id;
        let seg = synth.get(id).cloned().unwrap_or_default();
        let lseg = lec_log.get(id).cloned().unwrap_or_default();
        let check = read(&format!("{id}.check.rpt"));
        let mut problems = Vec::new();
        if seg.is_empty() {
            problems.push("no log segment (the session stopped before this design)".to_string());
        }
        let (measured, lec) = match cfg.tool {
            Tool::Dc => (
                parse::dc(
                    &read(&format!("{id}.area.rpt")),
                    &read(&format!("{id}.qor.rpt")),
                    &read(&format!("{id}.power.rpt")),
                    kit.time_unit_ps,
                ),
                parse::formality(&read(&format!("{id}.lec.rpt"))),
            ),
            Tool::Genus => (
                parse::genus(
                    &read(&format!("{id}.area.rpt")),
                    &read(&format!("{id}.timing.rpt")),
                    &read(&format!("{id}.power.rpt")),
                    id,
                ),
                parse::conformal(&read(&format!("{id}.lec.rpt"))),
            ),
            Tool::Yosys => (
                parse::yosys(
                    &read(&format!("{id}.area.rpt")),
                    &read(&format!("{id}.log")),
                    id,
                    j.period_ps,
                ),
                parse::abc_cec(&read(&format!("{id}.lec.rpt"))),
            ),
        };
        problems.extend(problems_of(
            kit,
            &seg,
            &lseg,
            &check,
            &read(&format!("{id}.net.v")),
            &measured,
            &lec,
        ));
        // Copy the evidence.
        let rel_dir = format!("{}/{}", kit.name, j.target);
        let netlist = format!("netlist/{rel_dir}/{id}.v");
        let net_text = read(&format!("{id}.net.v"));
        write(&out_root.join(&netlist), &net_text)?;
        let mut reports = Vec::new();
        for what in ["area", "qor", "timing", "power", "check", "lec"] {
            let src = j.dir.join(format!("{id}.{what}.rpt"));
            if src.is_file() {
                let rel = format!("reports/{rel_dir}/{id}.{what}.rpt");
                std::fs::copy(&src, out_root.join(&rel))
                    .or_else(|_| {
                        std::fs::create_dir_all(out_root.join(format!("reports/{rel_dir}")))?;
                        std::fs::copy(&src, out_root.join(&rel))
                    })
                    .map_err(|e| PassError::failed(format!("{rel}: {e}")))?;
                reports.push(rel);
            }
        }
        let log_rel = format!("reports/{rel_dir}/{id}.log");
        let yosys_log = if cfg.tool == Tool::Yosys {
            read(&format!("{id}.log"))
        } else {
            String::new()
        };
        write(
            &out_root.join(&log_rel),
            &format!("{seg}{yosys_log}@@lec\n{lseg}"),
        )?;
        reports.push(log_rel);
        out.push((
            Row {
                key: p.key.clone(),
                id: id.clone(),
                kind: p.kind,
                op: p.op.clone(),
                variant: p.variant.clone(),
                family: p.family.clone(),
                types: p.types.clone(),
                width: p.width,
                kit: kit.name.clone(),
                corner: kit.corner.clone(),
                target: j.target.clone(),
                period_ps: j.period_ps,
                designware: cfg.tool == Tool::Dc && parse::designware(&seg),
                measured,
                estimator: cfg.tool.name().into(),
                lec_tool: cfg.tool.lec().into(),
                lec,
                provisional: p.provisional,
                netlist,
                netlist_hash: canon::hash_bytes(net_text.as_bytes()),
                reports,
            },
            problems,
        ));
    }
    Ok(out)
}

/// Everything wrong with one design's synthesis and equivalence check. Shared with `verify`, which
/// calls it on the copies in `out/library/`.
pub fn problems_of(
    kit: &Kit,
    seg: &str,
    lec_seg: &str,
    check: &str,
    netlist: &str,
    m: &parse::Measured,
    lec: &parse::Lec,
) -> Problems {
    let mut p = Vec::new();
    for e in parse::errors(seg).into_iter().chain(parse::errors(lec_seg)) {
        p.push(format!("tool error: {e}"));
    }
    let u = parse::unresolved(seg, check);
    if u > 0 {
        p.push(format!("{u} unresolved references"));
    }
    if netlist.trim().is_empty() {
        p.push("no netlist".into());
    } else {
        let n = eda::netlist::parse(netlist);
        let latches = n.count_of(&kit.latches);
        if latches > 0 {
            p.push(format!("{latches} latch cells in the netlist"));
        }
        let foreign: Vec<&String> = n.foreign(&kit.cells).collect();
        if !foreign.is_empty() {
            p.push(format!(
                "cells outside {}: {}",
                kit.lib_name,
                foreign
                    .iter()
                    .take(5)
                    .map(|s| s.as_str())
                    .collect::<Vec<_>>()
                    .join(", ")
            ));
        }
    }
    if m.area_um2.is_none_or(|a| a <= 0.0) && !netlist.trim().is_empty() && !is_wiring(netlist) {
        p.push("no area in the report".into());
    }
    if m.delay_ps.is_none() && !is_wiring(netlist) {
        p.push("no delay in the report".into());
    }
    if !lec.equivalent {
        p.push(format!(
            "equivalence not proven: {} ({} failing, {} aborted, {} passing)",
            lec.verdict, lec.failing, lec.aborted, lec.passing
        ));
    }
    p
}

/// A netlist with no cell instances at all (a conversion that is only wires: sign extension,
/// truncation): it has zero area and no timing path.
pub fn is_wiring(netlist: &str) -> bool {
    let n = eda::netlist::parse(netlist);
    n.instances.keys().all(|t| n.modules.contains(t))
}
