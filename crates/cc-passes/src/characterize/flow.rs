/// The environment's directory (`build/.env/`): `chipc doctor` writes the `.db` files and the merged
/// ASAP7 Liberty there.
pub fn env_dir(ctx: &PassContext) -> PassDir {
    ArtifactStore::new(ctx.resolve(&ctx.paths().build_dir)).pass_dir(ENV_DIR)
}

fn missing(what: &Path) -> String {
    format!("{} is missing: run `chipc doctor` first", what.display())
}

/// The kits of the run: `cfg.pdks`, or every PDK manifest when it is empty.
pub fn kit_names(ctx: &PassContext, cfg: &CharacterizeConfig) -> Result<Vec<String>, String> {
    if cfg.pdks.is_empty() {
        ctx.pdk_names().map_err(|e| e.to_string())
    } else {
        Ok(cfg.pdks.clone())
    }
}

/// The kits of the run, from their PDK manifests and `chipc doctor`'s libraries, with what the rows
/// record about them.
pub fn kits(ctx: &PassContext, cfg: &CharacterizeConfig) -> Result<Vec<(Kit, KitInfo)>, String> {
    let pdks = kit_names(ctx, cfg)?
        .iter()
        .map(|n| ctx.pdk(n).map_err(|e| e.to_string()))
        .collect::<Result<Vec<_>, _>>()?;
    kits_of(&env_dir(ctx), &pdks, cfg)
}

/// [`kits`] from the manifests and the environment's directory (`build/.env/`).
pub fn kits_of(env: &PassDir, pdks: &[Pdk], cfg: &CharacterizeConfig) -> Result<Vec<(Kit, KitInfo)>, String> {
    let db_dir = env.out_dir().join("pdk_db");
    let mut out = Vec::new();
    for pdk in pdks {
        let name = pdk.name().to_string();
        // A kit shipped as group libraries is linked as the one library `chipc doctor` merged them into.
        let liberty = match pdk.merged_name() {
            Some(m) => env.out_dir().join("pdk_lib").join(format!("{m}.lib")),
            None => pdk
                .liberty_files()
                .map_err(|e| e.to_string())?
                .into_iter()
                .next()
                .ok_or_else(|| format!("{name}: no Liberty file"))?,
        };
        if !liberty.is_file() {
            return Err(missing(&liberty));
        }
        let lib = pdk_db::read_library(&liberty).map_err(|e| e.to_string())?;
        let db = db_dir.join(lib.db_file());
        if !db.is_file() {
            return Err(missing(&db));
        }
        let text = std::fs::read_to_string(&liberty).map_err(|e| format!("{}: {e}", liberty.display()))?;
        let cell = cfg.driving_cell.get(&name).unwrap_or(&pdk.manifest.driving_cell);
        let clock_ps = cfg.clock_ps.get(&name).copied().unwrap_or(pdk.manifest.clock_ps);
        let kit = eda::kit(&name, &text, liberty.clone(), db.clone(), cell, cfg.load_fanout)?;
        let hash = |p: &Path| canon::hash_file(p).map_err(|e| e.to_string());
        let info = KitInfo {
            name: name.clone(),
            corner: kit.corner.clone(),
            lib_name: kit.lib_name.clone(),
            liberty: liberty.display().to_string(),
            liberty_hash: hash(&liberty)?,
            db: db.display().to_string(),
            db_hash: hash(&db)?,
            time_unit_ps: kit.time_unit_ps,
            driving_cell: kit.driving_cell.clone(),
            load: kit.load,
            clock_ps,
        };
        out.push((kit, info));
    }
    Ok(out)
}

/// The versions of the licensed tools as `chipc doctor` recorded them (its manifest).
pub fn eda_versions(ctx: &PassContext) -> BTreeMap<String, String> {
    env_dir(ctx)
        .read_manifest()
        .ok()
        .flatten()
        .map(|m| m.tool_versions)
        .unwrap_or_default()
}

/// A design per primitive with RTL: its own file after its dependencies'.
pub fn design(p: &Primitive) -> Design {
    let mut files: Vec<String> = p.deps.iter().map(|d| format!("{d}.v")).collect();
    files.push(format!("{}.v", p.id));
    Design {
        id: p.id.clone(),
        files,
        clocked: p.clocked,
    }
}

const RTL_SCRIPT: &str = r#"#!/bin/bash
# Generated by chipc characterize: DSLX -> IR -> optimized IR -> combinational Verilog.
set -u
for x in *.x; do
  id="${x%.x}"
  if ir_converter_main --dslx_stdlib_path="$XLS_STDLIB" --top="$id" "$x" > "$id.ir" 2> "$id.err"; then
    top="$(sed -n 's/^top fn \([^(]*\)(.*/\1/p' "$id.ir")"
    if opt_main "$id.ir" --top="$top" > "$id.opt.ir" 2>> "$id.err" \
       && codegen_main "$id.opt.ir" --top="$top" --generator=combinational --use_system_verilog=false \
            --module_name="$id" --output_verilog_path="$id.v" 2>> "$id.err"; then
      :
    else
      echo "Error: optimization or codegen failed on $id"
    fi
  else
    echo "Error: IR conversion failed on $id"
  fi
done
echo "@@done"
"#;

/// The RTL job directory's name: `rtl-` and the hash of the image, the script and every source.
pub fn rtl_dir_name(image: &str, cat: &[Primitive]) -> String {
    let mut key = format!("rtl\n{image}\n{RTL_SCRIPT}");
    for p in cat {
        if let Some(s) = &p.source {
            key.push_str(&format!("{}\n{:?}\n", p.id, s));
        }
    }
    format!("rtl-{}", short(&key))
}

/// RTL for every primitive with a source: Verilog sources as they are, DSLX through XLS in one container.
/// The job directory is named by the hash of the sources and the image, so a rerun reuses it.
pub fn rtl(ctx: &PassContext, cat: &[Primitive]) -> Result<PathBuf, PassError> {
    let fail = |e: String| PassError::failed(e);
    let dir = ctx.dir().path().join("eda").join(rtl_dir_name(&image(ctx), cat));
    let done = dir.join("rtl.done");
    if done.is_file() {
        return Ok(dir);
    }
    std::fs::create_dir_all(&dir).map_err(|e| fail(format!("{}: {e}", dir.display())))?;
    for p in cat {
        let (name, text) = match &p.source {
            Some(Source::Dslx(t)) => (format!("{}.x", p.id), t),
            Some(Source::Verilog(t)) => (format!("{}.v", p.id), t),
            None => continue,
        };
        write(&dir.join(name), text)?;
    }
    write(&dir.join("gen.sh"), RTL_SCRIPT)?;
    let inv = Invocation::new("xls-rtl", "bash")
        .arg("gen.sh")
        .cwd("/work")
        .mount(Mount {
            src: dir.clone(),
            dst: "/work".into(),
            readonly: false,
        });
    let o = ctx.docker().run(&inv)?;
    let out = o.stdout_string().unwrap_or_default();
    if !o.success() || !out.contains("@@done") {
        return Err(fail(format!(
            "RTL generation failed (exit {:?}); see {}",
            o.exit_code,
            o.stdout.display()
        )));
    }
    let errs = parse::errors(&out);
    if !errs.is_empty() {
        return Err(fail(format!("RTL generation: {}", errs.join("; "))));
    }
    for p in cat.iter().filter(|p| p.source.is_some()) {
        let v = dir.join(format!("{}.v", p.id));
        if std::fs::metadata(&v).map(|m| m.len() == 0).unwrap_or(true) {
            return Err(fail(format!(
                "no RTL for {}: see {}",
                p.id,
                dir.join(format!("{}.err", p.id)).display()
            )));
        }
    }
    write(&done, "ok\n")?;
    Ok(dir)
}

pub fn image(ctx: &PassContext) -> String {
    let d = &ctx.tools().docker;
    format!("{}:{}", d.image, d.tag)
}

fn short(s: &str) -> String {
    canon::hash_bytes(s.as_bytes()).chars().take(16).collect()
}

fn write(p: &Path, text: &str) -> Result<(), PassError> {
    if let Some(d) = p.parent() {
        std::fs::create_dir_all(d).map_err(|e| PassError::failed(format!("{}: {e}", d.display())))?;
    }
    std::fs::write(p, text).map_err(|e| PassError::failed(format!("{}: {e}", p.display())))
}

/// One tool session: a batch of designs on one kit at one timing point.
#[derive(Debug, Clone)]
pub struct Job {
    pub kit: usize,
    pub target: String,
    pub period_ps: f64,
    pub designs: Vec<Design>,
    /// Named by the hash of the synthesis inputs (scripts, RTL, libraries, image).
    pub dir: PathBuf,
    /// File name → text of the synthesis scripts.
    pub synth: Vec<(String, String)>,
    /// File name → text of the equivalence scripts; `lec.done` holds `lec_key`, so a changed check
    /// reruns without synthesizing again.
    pub lec: Vec<(String, String)>,
    pub lec_key: String,
}

/// What a finished step records.
#[derive(Debug, Clone, Serialize, Deserialize)]
struct Done {
    seconds: f64,
    #[serde(default)]
    key: String,
}

/// The jobs of a run, in a fixed order (kit, target, batch). A job's directory is named by the flow, the
/// library hashes, the image and the full text of every synthesis script and RTL file.
pub fn jobs(
    ctx: &PassContext,
    cfg: &CharacterizeConfig,
    kits: &[(Kit, KitInfo)],
    designs: &[Design],
    rtl_dir: &Path,
) -> Result<Vec<Job>, PassError> {
    job_list(
        cfg,
        kits,
        designs,
        rtl_dir,
        ctx.dir().path(),
        &image(ctx),
        session_caps(ctx.resources(), cfg),
    )
    .map_err(PassError::failed)
}

/// [`jobs`] of the pass directory `pass_dir` (the job directories are `pass_dir/eda/…`, DC's library
/// analysis `pass_dir/alib`), the image `image` and the session caps `caps`.
pub fn job_list(
    cfg: &CharacterizeConfig,
    kits: &[(Kit, KitInfo)],
    designs: &[Design],
    rtl_dir: &Path,
    pass_dir: &Path,
    image: &str,
    caps: Caps,
) -> Result<Vec<Job>, String> {
    let flow = cfg.flow()?;
    let alib = pass_dir.join("alib");
    let lec = cfg.lec_options();
    let mut out = Vec::new();
    for (ki, (kit, info)) in kits.iter().enumerate() {
        for target in &cfg.targets {
            let period = cfg.period_ps(info.clock_ps, target)?;
            for chunk in designs.chunks(cfg.batch) {
                let job = SynthJob {
                    kit,
                    designs: chunk,
                    period_ps: period,
                    caps,
                    cache_dir: &alib,
                    lec: lec.as_ref(),
                };
                let scripts = flow.synth_scripts(&job);
                let lec = flow.lec_scripts(&job);
                let mut key = format!(
                    "{}\n{}\n{}\n{}\n",
                    flow.name(),
                    info.liberty_hash,
                    info.db_hash,
                    image
                );
                for (f, t) in &scripts {
                    key.push_str(&format!("{f}\n{t}\n"));
                }
                for d in chunk {
                    for f in &d.files {
                        let text = std::fs::read_to_string(rtl_dir.join(f)).map_err(|e| format!("{f}: {e}"))?;
                        key.push_str(&format!("{f}\n{text}\n"));
                    }
                }
                let dir = pass_dir
                    .join("eda")
                    .join(format!("{}-{target}-{}", kit.name, short(&key)));
                let mut lec_key = String::new();
                for (f, t) in &lec {
                    lec_key.push_str(&format!("{f}\n{t}\n"));
                }
                out.push(Job {
                    kit: ki,
                    target: target.clone(),
                    period_ps: period,
                    designs: chunk.to_vec(),
                    dir,
                    synth: scripts,
                    lec_key: short(&lec_key),
                    lec,
                });
            }
        }
    }
    Ok(out)
}

/// Caps of one tool session: the pass's memory split over its parallel sessions, `cores` CPUs.
pub fn session_caps(r: &PassResources, cfg: &CharacterizeConfig) -> Caps {
    let par = r.threads.max(1) as f64;
    Caps {
        memory_gb: (r.memory_gb / par).max(1.0),
        cpus: f64::from(cfg.cores),
        timeout_s: r.timeout_min * 60.0,
        pids_limit: 1024,
    }
}

/// Run every job not already done, `threads` at a time (the license semaphore bounds the EDA calls).
/// Returns (run, reused, tool seconds).
pub fn run_jobs(
    ctx: &PassContext,
    cfg: &CharacterizeConfig,
    kits: &[(Kit, KitInfo)],
    jobs: &[Job],
    rtl_dir: &Path,
) -> Result<(u64, u64, f64), PassError> {
    let caps = session_caps(ctx.resources(), cfg);
    let lec = cfg.lec_options();
    let alib = ctx.dir().path().join("alib");
    let pool = rayon::ThreadPoolBuilder::new()
        .num_threads(ctx.resources().threads.max(1))
        .build()
        .map_err(|e| PassError::failed(e.to_string()))?;
    let results: Vec<Result<Option<f64>, PassError>> = pool.install(|| {
        jobs.par_iter()
            .with_max_len(1)
            .map(|j| {
                ctx.check_cancelled()?;
                let job = SynthJob {
                    kit: &kits[j.kit].0,
                    designs: &j.designs,
                    period_ps: j.period_ps,
                    caps,
                    cache_dir: &alib,
                    lec: lec.as_ref(),
                };
                run_job(ctx, cfg, &job, j, rtl_dir)
            })
            .collect()
    });
    let (mut ran, mut reused, mut secs) = (0u64, 0u64, 0.0);
    for r in results {
        match r? {
            Some(s) => {
                ran += 1;
                secs += s;
            }
            None => reused += 1,
        }
    }
    Ok((ran, reused, secs))
}

fn run_job(
    ctx: &PassContext,
    cfg: &CharacterizeConfig,
    job: &SynthJob,
    j: &Job,
    rtl_dir: &Path,
) -> Result<Option<f64>, PassError> {
    let flow = cfg.flow().map_err(PassError::failed)?;
    let synth_done = j.dir.join("synth.done");
    let lec_done = j.dir.join("lec.done");
    let lec_current = std::fs::read_to_string(&lec_done)
        .ok()
        .and_then(|t| serde_json::from_str::<Done>(&t).ok())
        .is_some_and(|d| d.key == j.lec_key);
    let need_synth = !synth_done.is_file();
    let need_lec = !j.lec.is_empty() && (need_synth || !lec_current);
    if !need_synth && !need_lec {
        return Ok(None);
    }
    let t0 = Instant::now();
    let runners = FlowRunners {
        eda: ctx.eda().with_caps(job.caps),
        docker: ctx.docker().with_caps(job.caps),
    };
    let done = |path: &Path, key: &str, t: Instant| {
        write(
            path,
            &serde_json::to_string(&Done {
                seconds: t.elapsed().as_secs_f64(),
                key: key.to_string(),
            })
            .unwrap_or_default(),
        )
    };
    if need_synth {
        std::fs::create_dir_all(j.dir.join("rtl")).map_err(|e| PassError::failed(e.to_string()))?;
        for d in &j.designs {
            for f in &d.files {
                std::fs::copy(rtl_dir.join(f), j.dir.join("rtl").join(f))
                    .map_err(|e| PassError::failed(format!("{f}: {e}")))?;
            }
        }
        for (f, t) in &j.synth {
            write(&j.dir.join(f), t)?;
        }
        flow.synthesize(&runners, job, &j.dir)?;
        done(&synth_done, "", t0)?;
    }
    if need_lec {
        let t1 = Instant::now();
        let _ = std::fs::remove_file(&lec_done);
        for d in &j.designs {
            let _ = std::fs::remove_file(j.dir.join(format!("{}.lec.rpt", d.id)));
        }
        for (f, t) in &j.lec {
            write(&j.dir.join(f), t)?;
        }
        flow.check_equivalence(&runners, job, &j.dir)?;
        done(&lec_done, &j.lec_key, t1)?;
    }
    Ok(Some(t0.elapsed().as_secs_f64()))
}

/// A design's problems found while reading its job (empty: the row stands).
pub type Problems = Vec<String>;

/// The rows of one job, its files copied into `out/library/` (`out_root`), and each design's problems.
pub fn rows(
    cfg: &CharacterizeConfig,
    kit: &Kit,
    j: &Job,
    cat: &BTreeMap<&str, &Primitive>,
    out_root: &Path,
) -> Result<Vec<(Row, Problems)>, PassError> {
    let flow = cfg.flow().map_err(PassError::failed)?;
    let caps = flow.capabilities();
    let read = |f: &str| std::fs::read_to_string(j.dir.join(f)).unwrap_or_default();
    let synth = parse::segments(&read("synth.log"));
    // A job directory may hold an earlier check's log; it counts only when the check is on.
    let lec_log = if cfg.lec {
        parse::segments(&read("lec.log"))
    } else {
        BTreeMap::new()
    };
    let mut out = Vec::new();
    for d in &j.designs {
        let p = cat[d.id.as_str()];
        let id = &d.id;
        let seg = synth.get(id).cloned();
        let ran = seg.is_some();
        let seg = seg.unwrap_or_default();
        let lseg = lec_log.get(id).cloned().unwrap_or_default();
        let check = read(&format!("{id}.check.rpt"));
        // A flow that writes a log per design (Yosys): its text, appended to the session's segment.
        let design_log = read(&format!("{id}.log"));
        let mut problems = Vec::new();
        if !ran {
            problems.push("no log segment (the session stopped before this design)".to_string());
        }
        let measured = flow.measure(
            &ReportTexts {
                area: &read(&format!("{id}.area.rpt")),
                qor: &read(&format!("{id}.qor.rpt")),
                timing: &read(&format!("{id}.timing.rpt")),
                power: &read(&format!("{id}.power.rpt")),
                log: &design_log,
            },
            id,
            j.period_ps,
            kit.time_unit_ps,
        );
        let lec = cfg
            .lec
            .then(|| flow.equivalence(&read(&format!("{id}.lec.rpt"))));
        let net_text = read(&format!("{id}.net.v"));
        let rtl_text = read(&format!("rtl/{id}.v"));
        problems.extend(problems_of(
            kit,
            &Evidence {
                seg: &seg,
                lec_seg: &lseg,
                check: &check,
                netlist: &net_text,
                rtl: &rtl_text,
                top: id,
                flops: expected_flops(p.kind, p.width),
                // ABC reports no path for a design that is only flip-flops.
                need_delay: caps.flop_only_paths || !d.clocked,
            },
            &measured,
            lec.as_ref(),
        ));
        let inconclusive = lec.as_ref().is_some_and(Lec::inconclusive);
        // Copy the evidence.
        let rel_dir = format!("{}/{}", kit.name, j.target);
        let netlist = format!("netlist/{rel_dir}/{id}.v");
        write(&out_root.join(&netlist), &net_text)?;
        let mut reports = Vec::new();
        for what in ["area", "qor", "timing", "power", "check", "lec"] {
            let src = j.dir.join(format!("{id}.{what}.rpt"));
            if src.is_file() && (what != "lec" || cfg.lec) {
                let rel = format!("reports/{rel_dir}/{id}.{what}.rpt");
                std::fs::copy(&src, out_root.join(&rel))
                    .or_else(|_| {
                        std::fs::create_dir_all(out_root.join(format!("reports/{rel_dir}")))?;
                        std::fs::copy(&src, out_root.join(&rel))
                    })
                    .map_err(|e| PassError::failed(format!("{rel}: {e}")))?;
                reports.push(rel);
            }
        }
        let log_rel = format!("reports/{rel_dir}/{id}.log");
        write(
            &out_root.join(&log_rel),
            &format!("{seg}{design_log}@@lec\n{lseg}"),
        )?;
        reports.push(log_rel);
        out.push((
            Row {
                key: p.key.clone(),
                id: id.clone(),
                kind: p.kind,
                op: p.op.clone(),
                variant: p.variant.clone(),
                family: p.family.clone(),
                types: p.types.clone(),
                width: p.width,
                kit: kit.name.clone(),
                corner: kit.corner.clone(),
                target: j.target.clone(),
                period_ps: j.period_ps,
                designware: flow.used_ip_blocks(&seg),
                measured,
                estimator: flow.name().into(),
                lec_tool: cfg.lec.then(|| caps.equivalence.to_string()),
                lec,
                inconclusive,
                provisional: p.provisional,
                netlist,
                netlist_hash: canon::hash_bytes(net_text.as_bytes()),
                reports,
            },
            problems,
        ));
    }
    Ok(out)
}

/// What one design left behind, as `problems_of` reads it.
#[derive(Debug, Clone, Copy)]
pub struct Evidence<'a> {
    /// The design's part of the synthesis and of the equivalence log.
    pub seg: &'a str,
    pub lec_seg: &'a str,
    pub check: &'a str,
    pub netlist: &'a str,
    /// The RTL file of the top module, and its name.
    pub rtl: &'a str,
    pub top: &'a str,
    /// Flip-flops the RTL describes (a register or accumulator: its width; otherwise none).
    pub flops: u64,
    /// Whether the report must have a timing path (ABC gives none for a design that is only flops).
    pub need_delay: bool,
}

/// The flip-flops a primitive's RTL describes.
pub fn expected_flops(kind: super::catalog::Kind, width: u32) -> u64 {
    match kind {
        super::catalog::Kind::Register | super::catalog::Kind::Accumulator => u64::from(width),
        _ => 0,
    }
}

/// Everything wrong with one design: the tool's log, the netlist against the library and the RTL (the
/// cheap checks: ports and widths, every output driven, flip-flops, library cells only, no latches, a
/// positive area), the reports, and the equivalence check when it ran. A check that ran out of time
/// without a failing point is not a problem by itself (`Lec::inconclusive`); with any other problem the
/// row fails. Shared with `verify`, which calls it on the copies in `out/library/`.
pub fn problems_of(kit: &Kit, e: &Evidence, m: &parse::Measured, lec: Option<&parse::Lec>) -> Problems {
    let mut p = Vec::new();
    for err in parse::errors(e.seg).into_iter().chain(parse::errors(e.lec_seg)) {
        p.push(format!("tool error: {err}"));
    }
    let u = parse::unresolved(e.seg, e.check);
    if u > 0 {
        p.push(format!("{u} unresolved references"));
    }
    let wiring = is_wiring(e.netlist);
    if e.netlist.trim().is_empty() {
        p.push("no netlist".into());
    } else {
        let n = eda::netlist::parse(e.netlist);
        let latches = n.count_of(&kit.latches);
        if latches > 0 {
            p.push(format!("{latches} latch cells in the netlist"));
        }
        let flops = n.count_of(&kit.flops);
        if flops != e.flops {
            p.push(format!(
                "{flops} flip-flops in the netlist, the RTL has {}",
                e.flops
            ));
        }
        let foreign: Vec<&String> = n.foreign(&kit.cells).collect();
        if !foreign.is_empty() {
            p.push(format!(
                "cells outside {}: {}",
                kit.lib_name,
                foreign
                    .iter()
                    .take(5)
                    .map(|s| s.as_str())
                    .collect::<Vec<_>>()
                    .join(", ")
            ));
        }
        match (
            eda::netlist::ports(e.rtl, e.top),
            eda::netlist::ports(e.netlist, e.top),
        ) {
            (Some(r), Some(nl)) if r == nl => {
                let open = eda::netlist::undriven_outputs(e.netlist, e.top);
                if !open.is_empty() {
                    p.push(format!("outputs not driven in the netlist: {}", open.join(", ")));
                }
            }
            (Some(r), Some(nl)) => p.push(format!("ports differ: RTL {r:?}, netlist {nl:?}")),
            (None, _) => p.push(format!("no module {} in the RTL", e.top)),
            (_, None) => p.push(format!("no module {} in the netlist", e.top)),
        }
        if !wiring && n.instances.is_empty() {
            p.push("no cells in the netlist".into());
        }
    }
    if m.area_um2.is_none_or(|a| a <= 0.0) && !e.netlist.trim().is_empty() && !wiring {
        p.push("no area in the report".into());
    }
    if e.need_delay && m.delay_ps.is_none() && !wiring {
        p.push("no delay in the report".into());
    }
    if let Some(lec) = lec
        && !lec.equivalent
        && !lec.inconclusive()
    {
        p.push(format!(
            "equivalence not proven: {} ({} failing, {} unverified, {} passing)",
            lec.verdict, lec.failing, lec.aborted, lec.passing
        ));
    }
    p
}

/// A netlist with no cell instances at all (a conversion that is only wires: sign extension,
/// truncation): it has zero area and no timing path.
pub fn is_wiring(netlist: &str) -> bool {
    let n = eda::netlist::parse(netlist);
    n.instances.keys().all(|t| n.modules.contains(t))
}
