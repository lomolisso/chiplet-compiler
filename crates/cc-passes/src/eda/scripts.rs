//! Script generators. Every script works in its job directory: the RTL is under `rtl/`, each design
//! writes `<id>.<what>.rpt` and `<id>.net.v`, and the tools that run several designs per session print
//! `@@begin <id>` / `@@end <id>` around each so that their log splits per design (`parse::segments`).
//!
//! Constraints (docs/passes/characterize.md §4.3): a virtual clock (or the `clk` port) at the period, in
//! the library's time unit; input and output delays 0; every input driven by the kit's driving cell and
//! every output loaded with the kit's load.

use std::path::Path;

use super::{Design, Kit};

/// Brace-quote a Tcl word unless it is a plain path.
pub fn tcl(s: &str) -> String {
    if s.chars()
        .all(|c| c.is_ascii_alphanumeric() || "/._-+".contains(c))
    {
        s.to_string()
    } else {
        format!("{{{s}}}")
    }
}

fn tcl_list<'a>(files: impl Iterator<Item = &'a String>) -> String {
    files
        .map(|f| tcl(&format!("rtl/{f}")))
        .collect::<Vec<_>>()
        .join(" ")
}

/// The Tcl commands that read a design's RTL: VHDL first (`vhdl`), then Verilog (`verilog`), each only
/// when the design has such files; `{}` stands for the file list.
fn tcl_read(d: &Design, vhdl: &str, verilog: &str) -> String {
    let mut s = String::new();
    if d.vhdl().next().is_some() {
        s.push_str(&vhdl.replace("{}", &tcl_list(d.vhdl())));
        s.push('\n');
    }
    if d.verilog().next().is_some() {
        s.push_str(&verilog.replace("{}", &tcl_list(d.verilog())));
        s.push('\n');
    }
    s
}

/// The vendor library DesignWare: Design Compiler links its synthetic library (`dw_foundation.sldb`, in
/// the installation's `libraries/syn`) for a design that instantiates its components.
pub const DESIGNWARE: &str = "designware";

fn num(x: f64) -> String {
    // Shortest round-trip form; the scripts are part of the cache key, so the text must be stable.
    let s = format!("{x}");
    if s.contains('.') || s.contains('e') {
        s
    } else {
        format!("{s}.0")
    }
}

/// Design Compiler: `compile_ultra -no_autoungroup` per design (hierarchy kept, so a split multiplier
/// reports its pieces), with DesignWare parts kept as their own blocks (`compile_ultra_ungroup_dw
/// false`: Formality then verifies a divider against its DesignWare model in seconds, where the
/// flattened one stays unproven for hours), and a persistent library-analysis directory.
pub fn dc(preamble: &str, kit: &Kit, designs: &[Design], period_ps: f64, alib: &Path) -> String {
    let db_dir = kit.db.parent().unwrap_or(Path::new("."));
    let db = kit
        .db
        .file_name()
        .map(|f| f.to_string_lossy().into_owned())
        .unwrap_or_default();
    let p = num(kit.period(period_ps));
    // A job with DesignWare components links DesignWare's synthetic library; every other job's script is
    // unchanged (its text is part of the job's key).
    let dw = designs
        .iter()
        .any(|d| d.libraries.iter().any(|l| l == DESIGNWARE));
    let (dw_path, link) = if dw {
        (
            " [file join $synopsys_root libraries syn]",
            "set synthetic_library [list dw_foundation.sldb]\nset link_library [concat * $target_library $synthetic_library]\nset dw_root_file [open dw_root.txt w]\nputs $dw_root_file $synopsys_root\nclose $dw_root_file",
        )
    } else {
        ("", "set link_library [concat * $target_library]")
    };
    let mut s = format!(
        "# Generated by chipc characterize: Design Compiler, {kit} at {period_ps} ps.\n{preamble}\nset search_path [list . {dir}{dw_path}]\nset target_library [list {db}]\n{link}\nset alib_library_analysis_path {alib}\nset_app_var compile_ultra_ungroup_dw false\n",
        kit = kit.name,
        dir = tcl(&db_dir.display().to_string()),
        db = tcl(&db),
        alib = tcl(&alib.display().to_string()),
    );
    for d in designs {
        let id = &d.id;
        s.push_str(&format!(
            "\necho \"@@begin {id}\"\nremove_design -all\nset_svf {id}.svf\n{read}elaborate {id}\ncurrent_design {id}\nlink\ncheck_design > {id}.check.rpt\n",
            read = tcl_read(d, "analyze -format vhdl [list {}]", "analyze -format verilog [list {}]"),
        ));
        if d.clocked {
            s.push_str(&format!(
                "create_clock -name clk -period {p} [get_ports clk]\nset ins [remove_from_collection [all_inputs] [get_ports clk]]\nset_input_delay 0 -clock clk $ins\nset_output_delay 0 -clock clk [all_outputs]\nset_driving_cell -lib_cell {c} $ins\n",
                c = kit.driving_cell
            ));
        } else {
            s.push_str(&format!(
                "create_clock -name vclk -period {p}\nset_input_delay 0 -clock vclk [all_inputs]\nset_output_delay 0 -clock vclk [all_outputs]\nset_driving_cell -lib_cell {c} [all_inputs]\n",
                c = kit.driving_cell
            ));
        }
        s.push_str(&format!(
            "set_load {l} [all_outputs]\ncompile_ultra -no_autoungroup\nreport_qor > {id}.qor.rpt\nreport_area -hierarchy -nosplit > {id}.area.rpt\nreport_timing -nosplit > {id}.timing.rpt\nreport_power -nosplit > {id}.power.rpt\nwrite_file -format verilog -hierarchy -output {id}.net.v\nset_svf -off\necho \"@@end {id}\"\n",
            l = num(kit.load)
        ));
    }
    s.push_str("quit\n");
    s
}

/// Formality: RTL (reference) against the DC netlist (implementation) with DC's SVF guidance, one design
/// after the other in one session. Each verification stops after `timeout_min`; a design not proven is
/// verified again with each of `strategies` in turn (Formality's alternate strategies, `setup` first).
pub fn formality(
    preamble: &str,
    kit: &Kit,
    designs: &[Design],
    timeout_min: u32,
    strategies: &[String],
) -> String {
    let mut s = format!(
        "# Generated by chipc characterize: Formality, {}.\n{preamble}\nset verification_timeout_limit 0:{timeout_min}:0\n# XLS clamps array indices explicitly (`sel > N-1 ? N-1 : sel`); Formality still flags them as\n# possibly out of bounds (FMR_ELAB-147) and refuses to elaborate unless the message is a warning.\nset_mismatch_message_filter -warn FMR_ELAB-147\n",
        kit.name
    );
    // Formality elaborates instantiated DesignWare components only with the Synopsys tree that holds
    // them (`hdlin_dwroot`, else black boxes); Design Compiler wrote its own root for such a job.
    if designs
        .iter()
        .any(|d| d.libraries.iter().any(|l| l == DESIGNWARE))
    {
        s.push_str("set dw_root_file [open dw_root.txt r]\nset hdlin_dwroot [string trim [read $dw_root_file]]\nclose $dw_root_file\n");
    }
    let strat = strategies.iter().map(|x| tcl(x)).collect::<Vec<_>>().join(" ");
    for d in designs {
        let id = &d.id;
        s.push_str(&format!(
            "\necho \"@@begin {id}\"\nif {{[catch {{setup}}]}} {{}}\nset verification_alternate_strategy none\nremove_container -all\nremove_guidance\nset_svf {id}.svf\nread_db -technology_library {db}\n{read}set_top r:/WORK/{id}\nread_verilog -i {id}.net.v\nset_top i:/WORK/{id}\nmatch\nreport_unmatched_points > {id}.unmatched.rpt\nverify\nforeach s [list {strat}] {{\n  if {{[get_app_var verification_status] eq \"SUCCEEDED\"}} break\n  echo \"@@strategy $s\"\n  setup\n  set verification_alternate_strategy $s\n  match\n  verify\n}}\nreport_status > {id}.lec.rpt\necho \"@@end {id}\"\n",
            db = tcl(&kit.db.display().to_string()),
            read = tcl_read(d, "read_vhdl -r [list {}]", "read_verilog -r [list {}]"),
        ));
    }
    s.push_str("set verification_alternate_strategy none\nexit\n");
    s
}

/// Yosys + ABC in the image (a shell script; the Liberty file is mounted at `lib`): `synth`, `dfflibmap`,
/// ABC mapping at the period, `stat -liberty`; then, with `lec_timeout_s`, Yosys' equivalence flow
/// (`equiv_make` pairs the RTL's and the netlist's signals by name, `equiv_simple` and `equiv_induct` prove
/// each pair, registers included; that many seconds at most). The mapping is plain `map` without choice
/// computation (`dch`), which keeps the netlist close to the RTL's structure for the SAT-based proofs.
pub fn yosys(lib: &str, designs: &[Design], period_ps: f64, lec_timeout_s: Option<u64>) -> String {
    let mut s = String::from("#!/bin/bash\n# Generated by chipc characterize: Yosys + ABC.\nset -u\n");
    let d_ps = num(period_ps);
    for d in designs {
        let id = &d.id;
        if let Some(l) = d.libraries.first() {
            s.push_str(&format!(
                "echo \"@@begin {id}\"\necho \"Error: {id} instantiates the {l} library, which this flow does not link\"\necho \"@@end {id}\"\n"
            ));
            continue;
        }
        // VHDL (FloPoCo's operators) through the GHDL plugin: each file elaborates its entity, named
        // after the file.
        let mut read: Vec<String> = d
            .vhdl()
            .map(|f| {
                let unit = f.trim_end_matches(".vhdl");
                format!("ghdl --std=08 -fsynopsys rtl/{f} -e {unit}")
            })
            .collect();
        let v: Vec<String> = d.verilog().map(|f| format!("rtl/{f}")).collect();
        if !v.is_empty() {
            read.push(format!("read_verilog {}", v.join(" ")));
        }
        let read = read.join("; ");
        let m = if d.vhdl().next().is_some() { " -m ghdl" } else { "" };
        s.push_str(&format!(
            "echo \"@@begin {id}\"\nyosys{m} -q -l {id}.log -p \"{read}; hierarchy -check -top {id}; synth -top {id} -flatten -noshare; dfflibmap -liberty {lib}; abc -liberty {lib} -script +strash;map,-D,{d_ps};topo;stime,-p; opt_clean; stat -liberty {lib}; tee -o {id}.area.rpt stat -liberty {lib}; write_verilog -noattr {id}.net.v\" > /dev/null 2>&1 || echo \"Error: yosys failed on {id}\"\n",
        ));
        if let Some(timeout_s) = lec_timeout_s {
            s.push_str(&format!(
                "timeout {timeout_s} yosys{m} -q -l {id}.lec.rpt -p \"{read}; prep -top {id}; flatten; rename {id} gold; design -stash gold; read_liberty -ignore_miss_func {lib}; read_verilog {id}.net.v; prep -top {id}; flatten; rename {id} gate; design -stash gate; design -copy-from gold -as gold gold; design -copy-from gate -as gate gate; equiv_make gold gate eq; hierarchy -top eq; equiv_simple -seq 2; equiv_induct -seq 2; equiv_status -assert\" > /dev/null 2>&1 || echo \"equivalence not proven for {id}\" >> {id}.lec.rpt\n",
            ));
        }
        s.push_str(&format!("echo \"@@end {id}\"\n"));
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeSet;

    fn kit() -> Kit {
        Kit {
            name: "nangate45".into(),
            corner: "typical".into(),
            lib_name: "NangateOpenCellLibrary".into(),
            liberty: "/pdk/stdcells.lib".into(),
            db: "/env/out/pdk_db/NangateOpenCellLibrary.db".into(),
            time_unit_ps: 1000.0,
            driving_cell: "BUF_X1".into(),
            load: 3.6,
            cells: BTreeSet::new(),
            latches: BTreeSet::new(),
            flops: BTreeSet::new(),
        }
    }

    #[test]
    fn dc_script_constrains_in_the_library_unit() {
        let d = [
            Design {
                id: "add_i8".into(),
                files: vec!["add_i8.v".into()],
                clocked: false,
                libraries: Vec::new(),
            },
            Design {
                id: "register_w8".into(),
                files: vec!["register_w8.v".into()],
                clocked: true,
                libraries: Vec::new(),
            },
        ];
        let s = dc(
            "set_host_options -max_cores 2",
            &kit(),
            &d,
            2000.0,
            Path::new("/b/alib"),
        );
        assert!(s.contains("set target_library [list NangateOpenCellLibrary.db]"));
        assert!(s.contains("create_clock -name vclk -period 2.0\n"));
        assert!(s.contains("create_clock -name clk -period 2.0 [get_ports clk]"));
        assert!(s.contains("set_load 3.6 [all_outputs]"));
        assert_eq!(s.matches("@@begin").count(), 2);
        assert!(s.ends_with("quit\n"));
    }

    fn design(id: &str, files: &[&str], libraries: &[&str]) -> Design {
        Design {
            id: id.into(),
            files: files.iter().map(|f| f.to_string()).collect(),
            clocked: false,
            libraries: libraries.iter().map(|l| l.to_string()).collect(),
        }
    }

    #[test]
    fn designware_jobs_link_the_synthetic_library_and_others_stay_as_they_were() {
        let plain = dc(
            "",
            &kit(),
            &[design("add_i8", &["add_i8.v"], &[])],
            2000.0,
            Path::new("/a"),
        );
        assert!(plain.contains(
            "set search_path [list . /env/out/pdk_db]\nset target_library [list NangateOpenCellLibrary.db]\nset link_library [concat * $target_library]\n"
        ));
        assert!(!plain.contains("synthetic_library") && !plain.contains("vhdl"));
        assert!(
            plain.contains(
                "set_svf add_i8.svf\nanalyze -format verilog [list rtl/add_i8.v]\nelaborate add_i8\n"
            )
        );
        let dw = dc(
            "",
            &kit(),
            &[design("exp_f32", &["exp_f32.v"], &[DESIGNWARE])],
            2000.0,
            Path::new("/a"),
        );
        assert!(
            dw.contains(
                "set search_path [list . /env/out/pdk_db [file join $synopsys_root libraries syn]]\n"
            )
        );
        assert!(dw.contains(
            "set synthetic_library [list dw_foundation.sldb]\nset link_library [concat * $target_library $synthetic_library]\n"
        ));
    }

    #[test]
    fn vhdl_is_read_before_verilog_in_every_flow() {
        let d = [design("w", &["core.vhdl", "w.v"], &[])];
        let s = dc("", &kit(), &d, 2000.0, Path::new("/a"));
        assert!(s.contains(
            "analyze -format vhdl [list rtl/core.vhdl]\nanalyze -format verilog [list rtl/w.v]\nelaborate w\n"
        ));
        let f = formality("", &kit(), &d, 2, &[]);
        assert!(f.contains(
            "read_vhdl -r [list rtl/core.vhdl]\nread_verilog -r [list rtl/w.v]\nset_top r:/WORK/w\n"
        ));
        let y = yosys("/kit/x.lib", &d, 1000.0, Some(60));
        assert!(y.contains("yosys -m ghdl -q -l w.log -p \"ghdl --std=08 -fsynopsys rtl/core.vhdl -e core; read_verilog rtl/w.v; hierarchy -check -top w;"));
        assert!(y.contains("yosys -m ghdl -q -l w.lec.rpt -p \"ghdl --std=08 -fsynopsys rtl/core.vhdl -e core; read_verilog rtl/w.v; prep"));
        let plain = yosys("/kit/x.lib", &[design("a", &["a.v"], &[])], 1000.0, None);
        assert!(plain.contains("yosys -q -l a.log -p \"read_verilog rtl/a.v; hierarchy"));
        // A vendor library is not linked in this flow: the design reports an error instead of running.
        let dw = yosys(
            "/kit/x.lib",
            &[design("e", &["e.v"], &[DESIGNWARE])],
            1000.0,
            None,
        );
        assert!(dw.contains("Error: e instantiates the designware library") && !dw.contains("yosys -q"));
    }
}
