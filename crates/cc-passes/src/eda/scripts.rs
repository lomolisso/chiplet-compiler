//! Script generators. Every script works in its job directory: the RTL is under `rtl/`, each design
//! writes `<id>.<what>.rpt` and `<id>.net.v`, and the tools that run several designs per session print
//! `@@begin <id>` / `@@end <id>` around each so that their log splits per design (`parse::segments`).
//!
//! Constraints (docs/passes/characterize.md §4.3): a virtual clock (or the `clk` port) at the period, in
//! the library's time unit; input and output delays 0; every input driven by the kit's driving cell and
//! every output loaded with the kit's load.

use std::path::Path;

use super::{Design, Kit};

/// Brace-quote a Tcl word unless it is a plain path.
pub fn tcl(s: &str) -> String {
    if s.chars()
        .all(|c| c.is_ascii_alphanumeric() || "/._-+".contains(c))
    {
        s.to_string()
    } else {
        format!("{{{s}}}")
    }
}

fn files(d: &Design) -> String {
    d.files
        .iter()
        .map(|f| tcl(&format!("rtl/{f}")))
        .collect::<Vec<_>>()
        .join(" ")
}

fn num(x: f64) -> String {
    // Shortest round-trip form; the scripts are part of the cache key, so the text must be stable.
    let s = format!("{x}");
    if s.contains('.') || s.contains('e') {
        s
    } else {
        format!("{s}.0")
    }
}

/// Design Compiler: `compile_ultra -no_autoungroup` per design (hierarchy kept, so a split multiplier
/// reports its pieces), with a persistent library-analysis directory.
pub fn dc(preamble: &str, kit: &Kit, designs: &[Design], period_ps: f64, alib: &Path) -> String {
    let db_dir = kit.db.parent().unwrap_or(Path::new("."));
    let db = kit
        .db
        .file_name()
        .map(|f| f.to_string_lossy().into_owned())
        .unwrap_or_default();
    let p = num(kit.period(period_ps));
    let mut s = format!(
        "# Generated by chipc characterize: Design Compiler, {kit} at {period_ps} ps.\n{preamble}\nset search_path [list . {dir}]\nset target_library [list {db}]\nset link_library [concat * $target_library]\nset alib_library_analysis_path {alib}\n",
        kit = kit.name,
        dir = tcl(&db_dir.display().to_string()),
        db = tcl(&db),
        alib = tcl(&alib.display().to_string()),
    );
    for d in designs {
        let id = &d.id;
        s.push_str(&format!(
            "\necho \"@@begin {id}\"\nremove_design -all\nset_svf {id}.svf\nanalyze -format verilog [list {f}]\nelaborate {id}\ncurrent_design {id}\nlink\ncheck_design > {id}.check.rpt\n",
            f = files(d)
        ));
        if d.clocked {
            s.push_str(&format!(
                "create_clock -name clk -period {p} [get_ports clk]\nset ins [remove_from_collection [all_inputs] [get_ports clk]]\nset_input_delay 0 -clock clk $ins\nset_output_delay 0 -clock clk [all_outputs]\nset_driving_cell -lib_cell {c} $ins\n",
                c = kit.driving_cell
            ));
        } else {
            s.push_str(&format!(
                "create_clock -name vclk -period {p}\nset_input_delay 0 -clock vclk [all_inputs]\nset_output_delay 0 -clock vclk [all_outputs]\nset_driving_cell -lib_cell {c} [all_inputs]\n",
                c = kit.driving_cell
            ));
        }
        s.push_str(&format!(
            "set_load {l} [all_outputs]\ncompile_ultra -no_autoungroup\nreport_qor > {id}.qor.rpt\nreport_area -hierarchy -nosplit > {id}.area.rpt\nreport_timing -nosplit > {id}.timing.rpt\nreport_power -nosplit > {id}.power.rpt\nwrite_file -format verilog -hierarchy -output {id}.net.v\nset_svf -off\necho \"@@end {id}\"\n",
            l = num(kit.load)
        ));
    }
    s.push_str("quit\n");
    s
}

/// Formality: RTL (reference) against the DC netlist (implementation) with DC's SVF guidance, one design
/// after the other in one session.
pub fn formality(preamble: &str, kit: &Kit, designs: &[Design]) -> String {
    let mut s = format!(
        "# Generated by chipc characterize: Formality, {}.\n{preamble}\n",
        kit.name
    );
    for d in designs {
        let id = &d.id;
        s.push_str(&format!(
            "\necho \"@@begin {id}\"\nif {{[catch {{setup}}]}} {{}}\nremove_container -all\nremove_guidance\nset_svf {id}.svf\nread_db -technology_library {db}\nread_verilog -r [list {f}]\nset_top r:/WORK/{id}\nread_verilog -i {id}.net.v\nset_top i:/WORK/{id}\nmatch\nreport_unmatched_points > {id}.unmatched.rpt\nverify\nreport_status > {id}.lec.rpt\necho \"@@end {id}\"\n",
            db = tcl(&kit.db.display().to_string()),
            f = files(d)
        ));
    }
    s.push_str("exit\n");
    s
}

/// Genus: `syn_generic`, `syn_map`, `syn_opt` per design.
pub fn genus(preamble: &str, kit: &Kit, designs: &[Design], period_ps: f64) -> String {
    let p = num(kit.period(period_ps));
    let mut s = format!(
        "# Generated by chipc characterize: Genus, {kit} at {period_ps} ps.\n{preamble}\nset_db / .information_level 1\nread_libs {lib}\n",
        kit = kit.name,
        lib = tcl(&kit.liberty.display().to_string())
    );
    for d in designs {
        let id = &d.id;
        s.push_str(&format!(
            "\nputs \"@@begin {id}\"\nif {{[llength [get_db designs]] > 0}} {{ delete_obj [get_db designs] }}\nread_hdl -language v2001 [list {f}]\nelaborate {id}\ncheck_design -unresolved > {id}.check.rpt\n",
            f = files(d)
        ));
        let clock = if d.clocked {
            format!("create_clock -name clk -period {p} [get_db ports clk]\n")
        } else {
            format!("create_clock -name vclk -period {p}\n")
        };
        s.push_str(&clock);
        s.push_str(&format!(
            "set ins [get_db ports -if {{.direction == in && .base_name != clk}}]\nset outs [get_db ports -if {{.direction == out}}]\nset_input_delay 0 -clock [lindex [get_db clocks] 0] $ins\nset_output_delay 0 -clock [lindex [get_db clocks] 0] $outs\nset_driving_cell -lib_cell {c} $ins\nset_load {l} $outs\nsyn_generic\nsyn_map\nsyn_opt\nreport_qor > {id}.qor.rpt\nreport_area > {id}.area.rpt\nreport_timing > {id}.timing.rpt\nreport_power > {id}.power.rpt\nwrite_hdl > {id}.net.v\nputs \"@@end {id}\"\n",
            c = kit.driving_cell,
            l = num(kit.load)
        ));
    }
    s.push_str("exit\n");
    s
}

/// Conformal LEC (`-XL`, datapath analysis) of one design: RTL (golden) against the netlist (revised).
pub fn conformal(preamble: &str, kit: &Kit, d: &Design) -> String {
    let id = &d.id;
    let rtl: Vec<String> = d.files.iter().map(|f| format!("rtl/{f}")).collect();
    format!(
        "// Generated by chipc characterize: Conformal LEC, {kit}.\n{preamble}\nset log file {id}.lec.rpt -replace\nread library -liberty {lib} -both\nread design -verilog {rtl} -golden -root {id}\nread design -verilog {id}.net.v -revised -root {id}\nset system mode lec\nadd compared points -all\nanalyze datapath -verbose\ncompare\nreport verification\nreport compare data -class nonequivalent\nreport unmapped points -notmapped\nexit -force\n",
        kit = kit.name,
        lib = kit.liberty.display(),
        rtl = rtl.join(" ")
    )
}

/// Yosys + ABC in the image (a shell script; the Liberty file is mounted at `lib`): `synth`, `dfflibmap`,
/// ABC mapping at the period, `stat -liberty`; then ABC's `cec` (`dsec` for clocked designs) between the
/// RTL's AIG and the mapped netlist's.
pub fn yosys(lib: &str, designs: &[Design], period_ps: f64) -> String {
    let mut s = String::from("#!/bin/bash\n# Generated by chipc characterize: Yosys + ABC.\nset -u\n");
    let d_ps = num(period_ps);
    for d in designs {
        let id = &d.id;
        let f = d
            .files
            .iter()
            .map(|f| format!("rtl/{f}"))
            .collect::<Vec<_>>()
            .join(" ");
        s.push_str(&format!(
            "echo \"@@begin {id}\"\nyosys -q -l {id}.log -p \"read_verilog {f}; hierarchy -check -top {id}; synth -top {id} -flatten; dfflibmap -liberty {lib}; abc -liberty {lib} -script +strash;dch,-f;map,-D,{d_ps};topo;stime,-p; opt_clean; stat -liberty {lib}; tee -o {id}.area.rpt stat -liberty {lib}; write_verilog -noattr {id}.net.v\" > /dev/null 2>&1 || echo \"Error: yosys failed on {id}\"\n",
        ));
        s.push_str(&format!(
            "yosys -q -p \"read_verilog {f}; synth -top {id} -flatten; aigmap; write_aiger -zinit {id}.gold.aig; design -reset; read_liberty -ignore_miss_func {lib}; read_verilog {id}.net.v; hierarchy -top {id}; flatten; techmap; aigmap; write_aiger -zinit {id}.gate.aig\" > {id}.aig.log 2>&1 || echo \"Error: aiger export failed on {id}\"\nyosys-abc -c \"{cmd} {id}.gold.aig {id}.gate.aig\" > {id}.lec.rpt 2>&1 || echo \"Error: abc failed on {id}\"\necho \"@@end {id}\"\n",
            cmd = if d.clocked { "dsec" } else { "cec" }
        ));
    }
    s
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::collections::BTreeSet;

    fn kit() -> Kit {
        Kit {
            name: "nangate45".into(),
            corner: "typical".into(),
            lib_name: "NangateOpenCellLibrary".into(),
            liberty: "/pdk/stdcells.lib".into(),
            db: "/env/out/pdk_db/NangateOpenCellLibrary.db".into(),
            time_unit_ps: 1000.0,
            driving_cell: "BUF_X1".into(),
            load: 3.6,
            cells: BTreeSet::new(),
            latches: BTreeSet::new(),
        }
    }

    #[test]
    fn dc_script_constrains_in_the_library_unit() {
        let d = [
            Design {
                id: "add_i8".into(),
                files: vec!["add_i8.v".into()],
                clocked: false,
            },
            Design {
                id: "register_w8".into(),
                files: vec!["register_w8.v".into()],
                clocked: true,
            },
        ];
        let s = dc(
            "set_host_options -max_cores 2",
            &kit(),
            &d,
            2000.0,
            Path::new("/b/alib"),
        );
        assert!(s.contains("set target_library [list NangateOpenCellLibrary.db]"));
        assert!(s.contains("create_clock -name vclk -period 2.0\n"));
        assert!(s.contains("create_clock -name clk -period 2.0 [get_ports clk]"));
        assert!(s.contains("set_load 3.6 [all_outputs]"));
        assert_eq!(s.matches("@@begin").count(), 2);
        assert!(s.ends_with("quit\n"));
    }
}
