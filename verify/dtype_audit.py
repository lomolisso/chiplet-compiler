"""Check that every GEMM / convolution of a port computes in its recipe's datatypes.

    python -m verify.dtype_audit [key ...] [--cfg reduced|full] [--report]

For each model in models/quant_recipes.RECIPES (or the keys given), every phase is
lowered abstractly (no execution) and each dot_general / convolution is classified by
"<kind> <lhs>x<rhs>-><accumulator>". Every signature must be in the recipe's
audit["allow"], every audit["require"] signature must occur in some phase, and every
dtype named in audit["params"] (e.g. "int4", "float8_e4m3fn") must be the storage
dtype of some parameter. Optional, per phase:
  audit["phases"][phase] = {"allow": {...}, "require": [...]}  replaces the global allow
        list for that phase (e.g. SDXL: fp32 convs legal in vae_decode, not in unet_step)
  audit["counts"][cfg][phase] = {signature: n}  exact op counts at a config (e.g. every
        UNet layer FP8 except the 36 listed fp16 carve-outs)

With --report, writes verify/reports/dtype_histogram_<cfg>.md: per model and phase, op count
and GFLOP per signature, and per-invocation totals weighted by the phase trip counts
(the numbers hardware mapping needs).
"""

from __future__ import annotations

import argparse
import collections
import os
import sys

import jax

from models.quant_recipes import RECIPES
from verify import hlo

REPORTS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "reports")


def audit(key: str, cfg_name: str = "reduced"):
    mod = hlo.load(key)
    spec = mod.build(mod.CONFIGS[cfg_name])
    trips = {p.name: p.trip_count for p in spec.phases}
    texts = hlo.lower_phases(key, cfg_name)
    per_phase = {ph: hlo.summarize(hlo.census(text)) for ph, text in texts.items()}
    have = {str(l.dtype) for l in jax.tree_util.tree_leaves(spec.param_specs)}
    return per_phase, trips, check(RECIPES[key], per_phase, cfg_name, have)


def check(rec: dict, per_phase: dict, cfg_name: str, param_dtypes: set[str]) -> list[str]:
    """The recipe's audit over {phase: {signature: {"count", ...}}} (also used by cc_export)."""
    aud = rec["audit"]
    seen, errors = set(), []
    for ph, summ in per_phase.items():
        ph_aud = aud.get("phases", {}).get(ph, {})
        allow = ph_aud.get("allow", aud["allow"])
        for sig in summ:
            seen.add(sig)
            if sig not in allow:
                errors.append(f"{ph}: {sig} x{summ[sig]['count']} not allowed by the recipe")
        for sig in ph_aud.get("require", []):
            if sig not in summ:
                errors.append(f"{ph}: required {sig} not found")
        for sig, n in aud.get("counts", {}).get(cfg_name, {}).get(ph, {}).items():
            got = summ.get(sig, {"count": 0})["count"]
            if got != n:
                errors.append(f"{ph}: {sig} x{got}, recipe expects x{n}")
    for sig in aud.get("require", []):
        if sig not in seen:
            errors.append(f"required {sig} not found")
    # Parameter storage dtypes (weight-only and storage-only recipes do not show in the
    # GEMM signatures): every dtype in audit["params"] must be stored by some parameter.
    want = aud.get("params", {})
    for dt in want:
        if dt not in param_dtypes:
            errors.append(f"no parameter stored as {dt} ({want[dt]})")
    return errors


def _histogram_md(results, cfg_name) -> str:
    lines = [f"# GEMM / convolution datatypes per model ({cfg_name} config)", "",
             "Generated by `python -m verify.dtype_audit --report`. Signature = "
             "`<op> <lhs>x<rhs>-><accumulator>` (StableHLO element types). GFLOP = 2 x MACs per "
             "call; 'per invocation' multiplies by the phase trip count.", ""]
    for key, (per_phase, trips, errors) in results.items():
        rec = RECIPES[key]
        lines += [f"## {key}: {rec['recipe']}", "",
                  f"Audit: {'PASS' if not errors else 'FAIL: ' + '; '.join(errors)}", "",
                  "| phase | trips | signature | ops | GFLOP/call |", "|---|---|---|---|---|"]
        tot = collections.defaultdict(float)
        for ph, summ in per_phase.items():
            for sig, a in summ.items():
                lines.append(f"| {ph} | {trips[ph]} | `{sig}` | {a['count']} | {a['flops'] / 1e9:.4f} |")
                tot[sig] += a["flops"] * trips[ph]
        all_f = sum(tot.values()) or 1.0
        lines += ["", "Per invocation: " + ", ".join(
            f"`{s}` {f / 1e9:.3f} GFLOP ({100 * f / all_f:.1f}%)" for s, f in sorted(tot.items())), ""]
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("keys", nargs="*")
    ap.add_argument("--cfg", default="reduced")
    ap.add_argument("--report", action="store_true")
    a = ap.parse_args(argv)
    keys = a.keys or list(RECIPES)
    results, bad = {}, 0
    for key in keys:
        try:
            results[key] = audit(key, a.cfg)
        except Exception as e:                      # report and continue
            results[key] = ({}, {}, [f"lowering failed: {type(e).__name__}: {e}"])
        errs = results[key][2]
        bad += bool(errs)
        print(f"{key:22s} {'PASS' if not errs else 'FAIL'}")
        for e in errs[:10]:
            print(f"    {e}")
    if a.report:
        os.makedirs(REPORTS, exist_ok=True)
        with open(os.path.join(REPORTS, f"dtype_histogram_{a.cfg}.md"), "w") as f:
            f.write(_histogram_md(results, a.cfg))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
